type identifierGroup struct {
	typeName string
	prefix   string
	values   []string
}

func exportGoIdentifiers(catalog protocol.Catalog, writer io.Writer) error {
	if err := catalog.Validate(); err != nil {
		return err
	}
	groups := []identifierGroup{
		{typeName: "SemanticTypeID", prefix: "SemanticTypeID", values: collectIdentifiers(catalog.Types, func(value protocol.TypeDeclaration) string { return value.Identifier })},
		{typeName: "CapabilityID", prefix: "CapabilityID", values: collectIdentifiers(catalog.Capabilities, func(value protocol.CapabilityDeclaration) string { return string(value.Identifier) })},
		{typeName: "ActionKind", prefix: "ActionKind", values: collectIdentifiers(catalog.Actions, func(value protocol.ActionDeclaration) string { return value.Identifier })},
		{typeName: "EntityKind", prefix: "EntityKind", values: collectIdentifiers(catalog.Entities, func(value protocol.EntityDeclaration) string { return value.Identifier })},
		{typeName: "RelationID", prefix: "RelationID", values: collectIdentifiers(catalog.Relations, func(value protocol.RelationDeclaration) string { return value.Identifier })},
		{typeName: "ObservationID", prefix: "ObservationID", values: collectIdentifiers(catalog.Observations, func(value protocol.ObservationDeclaration) string { return value.Identifier })},
		{typeName: "EvidenceID", prefix: "EvidenceID", values: collectIdentifiers(catalog.Evidence, func(value protocol.EvidenceDeclaration) string { return value.Identifier })},
		{typeName: "PropertyID", prefix: "PropertyID", values: collectIdentifiers(catalog.Properties, func(value protocol.PropertyDeclaration) string { return value.Identifier })},
		{typeName: "PolicyKind", prefix: "PolicyKind", values: collectIdentifiers(catalog.Policies, func(value protocol.PolicyDeclaration) string { return value.Identifier })},
		{typeName: "FaultKind", prefix: "FaultKind", values: collectIdentifiers(catalog.Faults, func(value protocol.FaultDeclaration) string { return value.Identifier })},
		{typeName: "ModuleID", prefix: "ModuleID", values: collectIdentifiers(catalog.Modules, func(value protocol.ModuleDeclaration) string { return value.Identifier })},
		{typeName: "TargetID", prefix: "TargetID", values: collectIdentifiers(catalog.Targets, func(value protocol.TargetDeclaration) string { return value.Identifier })},
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by umpire3-export; DO NOT EDIT.\n\npackage protocol\n\n")
	fmt.Fprintf(&source, "const LeanVersion = %q\n\n", catalog.LeanVersion)
	for _, group := range groups {
		if group.typeName != "CapabilityID" {
			fmt.Fprintf(&source, "type %s string\n\n", group.typeName)
		}
		source.WriteString("const (\n")
		for _, value := range group.values {
			fmt.Fprintf(&source, "\t%s%s %s = %q\n", group.prefix, goIdentifier(value), group.typeName, value)
		}
		source.WriteString(")\n\n")
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated Go identifiers: %w", err)
	}
	if _, err := writer.Write(formatted); err != nil {
		return fmt.Errorf("write generated Go identifiers: %w", err)
	}
	return nil
}

func exportAuthorFacade(catalog protocol.Catalog, writer io.Writer) error {
	if err := catalog.Validate(); err != nil {
		return err
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by umpire3-export; DO NOT EDIT.\n\npackage scenario\n\n")
	source.WriteString("import \"go.temporal.io/server/tests/umpire3/protocol\"\n\n")

	for _, target := range catalog.Targets {
		name := goIdentifier(target.Identifier) + "Regression"
		fmt.Fprintf(&source, "// %s selects the %s model family.\n", name, target.Identifier)
		fmt.Fprintf(&source, "func %s(identifier string, resources []Resource, root Term) Scenario {\n", name)
		fmt.Fprintf(&source, "\treturn NewScenario(identifier, protocol.TargetID%s, resources, root)\n", goIdentifier(target.Identifier))
		source.WriteString("}\n\n")
	}
	for _, entity := range catalog.Entities {
		name := goIdentifier(entity.Identifier)
		fmt.Fprintf(&source, "// %s identifies %s\n", name, docSentence(entity.Description))
		fmt.Fprintf(&source, "func %s(identifier string) Resource {\n", name)
		fmt.Fprintf(&source, "\treturn Resource{Identifier: identifier, Kind: protocol.EntityKind%s}\n", name)
		source.WriteString("}\n\n")
	}
	for _, action := range catalog.Actions {
		name := goIdentifier(action.Identifier)
		fmt.Fprintf(&source, "// %s creates sparse intent to %s\n", name, lowerFirst(docSentence(action.Description)))
		fmt.Fprintf(&source, "func %s(identifier string, options ...ActionOption) Term {\n", name)
		fmt.Fprintf(&source, "\treturn actionAtCaller(identifier, protocol.ActionKind%s, options...)\n", name)
		source.WriteString("}\n\n")
	}
	type parameterFacade struct {
		valueType string
		values    []string
	}
	parameters := make(map[string]parameterFacade)
	var parameterOrder []string
	for _, action := range catalog.Actions {
		for _, parameter := range action.Parameters {
			existing, found := parameters[parameter.Name]
			if found {
				if existing.valueType != parameter.Type {
					return fmt.Errorf("action parameter %q has conflicting types %q and %q",
						parameter.Name, existing.valueType, parameter.Type)
				}
				existing.values = append(existing.values, parameter.Values...)
				slices.Sort(existing.values)
				existing.values = slices.Compact(existing.values)
				parameters[parameter.Name] = existing
				continue
			}
			parameterOrder = append(parameterOrder, parameter.Name)
			parameters[parameter.Name] = parameterFacade{
				valueType: parameter.Type, values: slices.Clone(parameter.Values),
			}
		}
	}
	for _, parameterName := range parameterOrder {
		parameter := parameters[parameterName]
		name := "With" + goIdentifier(parameterName)
		if len(parameter.values) != 0 {
			typeName := goIdentifier(parameterName) + "Mode"
			fmt.Fprintf(&source, "// %s identifies a supported %s action mode.\n", typeName, parameterName)
			fmt.Fprintf(&source, "type %s string\n\n", typeName)
			source.WriteString("const (\n")
			for _, value := range parameter.values {
				fmt.Fprintf(&source, "\t%s%s %s = %q\n",
					goIdentifier(parameterName), goIdentifier(value), typeName, value)
			}
			source.WriteString(")\n\n")
			fmt.Fprintf(&source, "// %s supplies the typed %s action parameter.\n", name, parameterName)
			fmt.Fprintf(&source, "func %s(value %s) ActionOption {\n", name, typeName)
			fmt.Fprintf(&source, "\treturn withStringArgument(%q, string(value))\n", parameterName)
			source.WriteString("}\n\n")
			continue
		}
		switch parameter.valueType {
		case "string":
			fmt.Fprintf(&source, "// %s supplies the typed %s action parameter.\n", name, parameterName)
			fmt.Fprintf(&source, "func %s(value string) ActionOption {\n", name)
			fmt.Fprintf(&source, "\treturn withStringArgument(%q, value)\n", parameterName)
		case "identity":
			fmt.Fprintf(&source, "// %s supplies the typed %s action parameter.\n", name, parameterName)
			fmt.Fprintf(&source, "func %s(value Symbol) ActionOption {\n", name)
			fmt.Fprintf(&source, "\treturn withIdentityArgument(%q, value)\n", parameterName)
		default:
			return fmt.Errorf("action parameter %q has unsupported facade type %q", parameterName, parameter.valueType)
		}
		source.WriteString("}\n\n")
	}
	for _, fault := range catalog.Faults {
		name := goIdentifier(fault.Identifier)
		fmt.Fprintf(&source, "// %s creates sparse fault intent for %s\n", name, lowerFirst(docSentence(fault.Description)))
		fmt.Fprintf(&source, "func %s(identifier string, options ...FaultOption) FaultIntent {\n", name)
		fmt.Fprintf(&source, "\treturn faultAtCaller(identifier, protocol.FaultKind%s, options...)\n", name)
		source.WriteString("}\n\n")
	}
	for _, property := range catalog.Properties {
		name := "Require" + goIdentifier(property.Identifier)
		fmt.Fprintf(&source, "// %s selects the proved property %s\n", name, docSentence(property.Description))
		fmt.Fprintf(&source, "func %s() Term {\n", name)
		fmt.Fprintf(&source, "\treturn requireAtCaller(protocol.PropertyID%s)\n", goIdentifier(property.Identifier))
		source.WriteString("}\n\n")
	}
	source.WriteString("const (\n")
	for _, observation := range catalog.Observations {
		name := "Outcome" + goIdentifier(observation.Identifier)
		fmt.Fprintf(&source, "\t// %s denotes %s\n", name, docSentence(observation.Description))
		fmt.Fprintf(&source, "\t%s protocol.ObservationID = protocol.ObservationID%s\n", name, goIdentifier(observation.Identifier))
	}
	source.WriteString(")\n\n")
	source.WriteString("const (\n")
	for _, relation := range catalog.Relations {
		name := "Relation" + goIdentifier(relation.Identifier)
		fmt.Fprintf(&source, "\t// %s denotes %s\n", name, docSentence(relation.Description))
		fmt.Fprintf(&source, "\t%s protocol.RelationID = protocol.RelationID%s\n", name, goIdentifier(relation.Identifier))
	}
	source.WriteString(")\n\n")
	source.WriteString("const (\n")
	for _, capability := range catalog.Capabilities {
		name := "Capability" + goIdentifier(string(capability.Identifier))
		fmt.Fprintf(&source, "\t// %s requests %s\n", name, docSentence(capability.Description))
		fmt.Fprintf(&source, "\t%s protocol.CapabilityID = protocol.CapabilityID%s\n", name, goIdentifier(string(capability.Identifier)))
	}
	source.WriteString(")\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated author facade: %w", err)
	}
	if _, err := writer.Write(formatted); err != nil {
		return fmt.Errorf("write generated author facade: %w", err)
	}
	return nil
}

func docSentence(value string) string {
	value = strings.TrimSpace(value)
	value = strings.TrimSuffix(value, ".")
	return value + "."
}

func lowerFirst(value string) string {
	characters := []rune(value)
	if len(characters) == 0 {
		return value
	}
	characters[0] = unicode.ToLower(characters[0])
	return string(characters)
}

func collectIdentifiers[T any](values []T, identifier func(T) string) []string {
	result := make([]string, len(values))
	for index, value := range values {
		result[index] = identifier(value)
	}
	return result
}

func goIdentifier(value string) string {
	parts := strings.FieldsFunc(value, func(character rune) bool {
		return !unicode.IsLetter(character) && !unicode.IsNumber(character)
	})
	var result strings.Builder
	for _, part := range parts {
		characters := []rune(part)
		if len(characters) == 0 {
			continue
		}
		result.WriteRune(unicode.ToUpper(characters[0]))
		result.WriteString(string(characters[1:]))
	}
	return result.String()
}

func exportExperimentSchema(writer io.Writer) error {
	stringValue := map[string]any{"type": "string", "minLength": 1}
	hashValue := map[string]any{"type": "string", "pattern": "^sha256:[0-9a-f]{64}$"}
	namedValue := closedObject([]string{"name", "value"}, map[string]any{
		"name": stringValue,
		"value": map[string]any{
			"type":                 "object",
			"additionalProperties": true,
			"required":             []string{"type"},
			"properties":           map[string]any{"type": stringValue},
		},
	})
	binding := closedObject([]string{"symbol", "type", "projection"}, map[string]any{
		"symbol": stringValue, "type": stringValue, "projection": stringValue,
	})
	schema := closedObject([]string{
		"formatVersion", "experimentID", "model", "property", "scope", "resources", "actions",
		"policies", "faults", "order", "checkpoints", "provenance", "retention",
	}, map[string]any{
		"formatVersion": map[string]any{"const": protocol.FormatVersion},
		"experimentID":  stringValue,
		"model": closedObject([]string{"modules", "sourceRevision", "semanticHash", "catalogHash", "leanVersion"}, map[string]any{
			"modules": arrayOf(stringValue), "sourceRevision": stringValue, "semanticHash": hashValue,
			"catalogHash": hashValue, "leanVersion": stringValue,
		}),
		"property": closedObject([]string{"identifier", "statementHash", "claim"}, map[string]any{
			"identifier": stringValue, "statementHash": hashValue,
			"claim": map[string]any{"const": "implementation-conformance"},
		}),
		"scope": closedObject([]string{"bounds", "assumptions", "strategy", "seed"}, map[string]any{
			"bounds": closedObject([]string{"maxDepth", "maxResults"}, map[string]any{
				"maxDepth": positiveInteger(), "maxResults": positiveInteger(),
			}),
			"assumptions": arrayOf(closedObject([]string{"identifier", "statementHash"}, map[string]any{
				"identifier": stringValue, "statementHash": hashValue,
			})),
			"strategy": stringValue, "seed": map[string]any{"type": "integer"},
		}),
		"resources": arrayOf(closedObject([]string{"identifier", "kind"}, map[string]any{
			"identifier": stringValue, "kind": stringValue,
		})),
		"actions": arrayOf(closedObject([]string{
			"identifier", "kind", "allowedOutcomes", "requiredCapabilities",
		}, map[string]any{
			"identifier": stringValue, "kind": stringValue, "arguments": arrayOf(namedValue),
			"allowedOutcomes": arrayOf(map[string]any{"enum": []string{
				"applied", "suppressed", "rejected", "retried", "fault-intercepted",
			}}),
			"bindings": arrayOf(binding), "requiredCapabilities": arrayOf(stringValue),
			"preCheckpoint": stringValue, "postCheckpoint": stringValue,
			"responseMode": map[string]any{"enum": []string{
				"synchronous", "asynchronous", "deferred", "blocking", "failure",
			}},
			"maxBlockNanos": map[string]any{"type": "integer", "minimum": 1},
		})),
		"policies": arrayOf(closedObject([]string{"identifier", "kind", "scope"}, map[string]any{
			"identifier": stringValue, "kind": stringValue, "scope": arrayOf(stringValue),
			"arguments": arrayOf(namedValue),
		})),
		"faults": arrayOf(closedObject([]string{
			"identifier", "kind", "safetyClass", "scope", "occurrence", "interval", "requiredCapabilities",
		}, map[string]any{
			"identifier": stringValue, "kind": stringValue, "policy": stringValue,
			"safetyClass": map[string]any{"enum": []string{"controlled", "restricted"}},
			"scope": closedObject([]string{
				"resources", "endpoints", "taskQueues", "services", "routes", "participants", "attempts",
			}, map[string]any{
				"resources": arrayOf(stringValue), "endpoints": arrayOf(stringValue),
				"taskQueues": arrayOf(stringValue), "services": arrayOf(stringValue),
				"routes": arrayOf(stringValue), "participants": arrayOf(stringValue),
				"attempts": arrayOf(positiveInteger()),
			}),
			"occurrence": closedObject([]string{"first", "count"}, map[string]any{
				"first": positiveInteger(), "count": positiveInteger(),
			}),
			"interval": closedObject([]string{"startAction", "stopAction"}, map[string]any{
				"startAction": stringValue, "stopAction": stringValue,
			}),
			"arguments": arrayOf(namedValue), "requiredCapabilities": arrayOf(stringValue),
		})),
		"order": arrayOf(closedObject([]string{"before", "after", "relation"}, map[string]any{
			"before": stringValue, "after": stringValue,
			"relation": map[string]any{"enum": []string{"user", "semantic", "same-source", "runtime-causal"}},
		})),
		"checkpoints": arrayOf(closedObject([]string{"identifier", "observation", "ordering", "omissionPolicy"}, map[string]any{
			"identifier": stringValue, "observation": stringValue,
			"ordering":       map[string]any{"enum": []string{"causal", "source-sequence", "none"}},
			"omissionPolicy": map[string]any{"enum": []string{"required", "optional"}},
		})),
		"provenance": closedObject([]string{"kind", "proofManifest"}, map[string]any{
			"kind":          map[string]any{"enum": []string{"proof", "bounded-exploration", "counterexample", "curated-trace"}},
			"proofManifest": stringValue,
		}),
		"retention": closedObject([]string{"redactionClass", "maxArtifactBytes"}, map[string]any{
			"redactionClass": map[string]any{"const": "semantic-only"}, "maxArtifactBytes": positiveInteger(),
		}),
	})
	schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
	schema["$id"] = "https://temporal.io/schemas/umpire3/experiment-v2.json"
	encoder := json.NewEncoder(writer)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(schema); err != nil {
		return fmt.Errorf("encode experiment schema: %w", err)
	}
	return nil
}

func closedObject(required []string, properties map[string]any) map[string]any {
	return map[string]any{
		"type":                 "object",
		"additionalProperties": false,
		"required":             required,
		"properties":           properties,
	}
}

func arrayOf(items any) map[string]any {
	return map[string]any{"type": "array", "items": items}
}

func positiveInteger() map[string]any {
	return map[string]any{"type": "integer", "minimum": 1}
}
