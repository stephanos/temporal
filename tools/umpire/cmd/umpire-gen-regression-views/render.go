package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

const generatedMarker = "// Code generated by umpire-gen-regression-views. DO NOT EDIT."

func renderGeneratedViews(records []generatedViewRecord) (map[string][]byte, error) {
	if len(records) == 0 {
		return nil, errors.New("render generated views: at least one generated view is required")
	}
	ordered := append([]generatedViewRecord(nil), records...)
	slices.SortFunc(ordered, func(left, right generatedViewRecord) int {
		return strings.Compare(left.Identity, right.Identity)
	})
	if err := validateGeneratedViewTestNames(ordered); err != nil {
		return nil, fmt.Errorf("render generated views: %w", err)
	}
	entries := make([]manifestEntry, 0, len(ordered))
	for _, record := range ordered {
		entries = append(entries, manifestEntry{
			Identity:           record.Identity,
			FixturePath:        record.FixturePath,
			GoOutputPath:       record.GoOutputPath,
			MarkdownOutputPath: record.MarkdownOutputPath,
		})
	}
	if err := validateManifest(entries); err != nil {
		return nil, fmt.Errorf("render generated views: %w", err)
	}

	artifacts := make(map[string][]byte, len(ordered)*2)
	for _, record := range ordered {
		goSource, err := renderGo(record)
		if err != nil {
			return nil, fmt.Errorf("render Go generated view %q: %w", record.Identity, err)
		}
		markdown := renderMarkdown(record)
		if err := validateRenderedPair(record, goSource, markdown); err != nil {
			return nil, err
		}
		artifacts[record.GoOutputPath] = goSource
		artifacts[record.MarkdownOutputPath] = markdown
	}
	return artifacts, nil
}

func renderGo(record generatedViewRecord) ([]byte, error) {
	var generated strings.Builder
	generated.WriteString(generatedMarker)
	generated.WriteString("\n// This verifies a Lean model generated view only; it does not execute Temporal or represent evidence.\n\n")
	generated.WriteString("package regression\n\n")
	generated.WriteString("import \"testing\"\n\n")
	fmt.Fprintf(&generated, "// %s verifies the checked-in generated view for %s.\n", record.TestName, record.Identity)
	for _, source := range record.Sources {
		fmt.Fprintf(&generated, "// Lean source: %s\n", source.RepositoryPath)
	}
	fmt.Fprintf(&generated, "// Artifact checksum: %s\n", record.ArtifactChecksum)
	fmt.Fprintf(&generated, "func %s(t *testing.T) {\n", record.TestName)
	generated.WriteString("\tRequireGeneratedView(t, Reference{\n")
	fmt.Fprintf(&generated, "\t\tFormatVersion: %q,\n", record.Format)
	fmt.Fprintf(&generated, "\t\tIdentity: %q,\n", record.Identity)
	fmt.Fprintf(&generated, "\t\tFixturePath: %q,\n", record.FixturePath)
	writeGoStringSlice(&generated, "Sources", canonicalSourcePaths(record.Sources))
	writeGoStringSlice(&generated, "Properties", record.Properties)
	writeGoStringSlice(&generated, "ObservationRequirements", record.ObservationRequirements)
	fmt.Fprintf(&generated, "\t\tArtifactChecksum: %q,\n", record.ArtifactChecksum)
	generated.WriteString("\t})\n}\n")
	formatted, err := format.Source([]byte(generated.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return formatted, nil
}

func writeGoStringSlice(generated *strings.Builder, field string, values []string) {
	fmt.Fprintf(generated, "\t\t%s: []string{\n", field)
	for _, value := range values {
		fmt.Fprintf(generated, "\t\t\t%q,\n", value)
	}
	generated.WriteString("\t\t},\n")
}

func renderMarkdown(record generatedViewRecord) []byte {
	var generated strings.Builder
	generated.WriteString("<!-- Code generated by umpire-gen-regression-views. DO NOT EDIT. -->\n")
	generated.WriteString("# Umpire regression generated views\n\n")
	generated.WriteString("> This is a model generated view only. It does not represent Temporal runtime execution, execution evidence, or conformance.\n\n")
	fmt.Fprintf(&generated, "## `%s`\n\n", record.Identity)
	fmt.Fprintf(&generated, "- Format: `%s`\n", record.Format)
	fmt.Fprintf(&generated, "- Canonical fixture: `%s`\n", record.FixturePath)
	fmt.Fprintf(&generated, "- Artifact checksum: `%s`\n", record.ArtifactChecksum)
	writeMarkdownSources(&generated, record.Sources)
	writeMarkdownList(&generated, "Properties", record.Properties)
	writeMarkdownList(&generated, "Observation requirements", record.ObservationRequirements)
	return []byte(generated.String())
}

func writeMarkdownSources(generated *strings.Builder, sources []sourceView) {
	generated.WriteString("\n### Lean sources\n\n")
	for _, source := range sources {
		fmt.Fprintf(
			generated,
			"- Canonical: `%s`; repository: `%s`\n",
			source.CanonicalPath,
			source.RepositoryPath,
		)
	}
}

func writeMarkdownList(generated *strings.Builder, title string, values []string) {
	fmt.Fprintf(generated, "\n### %s\n\n", title)
	for _, value := range values {
		fmt.Fprintf(generated, "- `%s`\n", value)
	}
}

func canonicalSourcePaths(sources []sourceView) []string {
	result := make([]string, 0, len(sources))
	for _, source := range sources {
		result = append(result, source.CanonicalPath)
	}
	return result
}

func validateRenderedPair(record generatedViewRecord, goSource, markdown []byte) error {
	expectedGo, err := renderGo(record)
	if err != nil {
		return fmt.Errorf("validate rendered generated view %q: %w", record.Identity, err)
	}
	expectedMarkdown := renderMarkdown(record)
	if !bytes.Equal(goSource, expectedGo) {
		return fmt.Errorf("validate rendered generated view %q: Go metadata diverges from generated view record", record.Identity)
	}
	if !bytes.Equal(markdown, expectedMarkdown) {
		return fmt.Errorf("validate rendered generated view %q: Markdown metadata diverges from generated view record", record.Identity)
	}
	return nil
}
