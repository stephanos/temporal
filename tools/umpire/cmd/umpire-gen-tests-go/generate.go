package main

import (
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"go.temporal.io/server/tools/umpire/artifact"
	"go.temporal.io/server/tools/umpire/runner"
	"go.temporal.io/server/tools/umpire/temporal/nexus"
)

const generatedTestFileName = "caller_closure_runner_generated_test.go"

type generationInput struct {
	packageName string
	embedRoot   string
	binding     runner.InputBinding
}

func run(args []string) error {
	if len(args) != 3 || args[1] != "--output" || args[0] == "" || args[2] == "" {
		return errors.New("expected <manifest> --output <package>")
	}
	input, err := loadGenerationInput(args[0], args[2])
	if err != nil {
		return err
	}
	generated, err := renderGeneratedTest(input)
	if err != nil {
		return err
	}
	return writeGeneratedTest(args[2], generated)
}

func loadGenerationInput(manifestPath, outputRoot string) (generationInput, error) {
	if filepath.Base(manifestPath) != "manifest.json" {
		return generationInput{}, errors.New("generated Go input must be an Artifact set manifest")
	}
	outputInfo, err := os.Lstat(outputRoot)
	if err != nil {
		return generationInput{}, fmt.Errorf("inspect output package: %w", err)
	}
	if outputInfo.Mode()&os.ModeSymlink != 0 || !outputInfo.IsDir() {
		return generationInput{}, errors.New("generated Go output must be a regular package directory")
	}
	packageName := filepath.Base(filepath.Clean(outputRoot))
	if !token.IsIdentifier(packageName) {
		return generationInput{}, errors.New("generated Go output package name is invalid")
	}

	setRoot := filepath.Dir(manifestPath)
	files := make(map[string][]byte, 3)
	for _, relative := range []string{
		"manifest.json",
		"artifacts/experiment.json",
		"artifacts/runtime-configuration.json",
	} {
		encoded, readErr := readRegularFile(filepath.Join(setRoot, filepath.FromSlash(relative)))
		if readErr != nil {
			return generationInput{}, fmt.Errorf("read executable Artifact set: %w", readErr)
		}
		files[relative] = encoded
	}
	admitted, err := artifact.AdmitSetFiles(files)
	if err != nil {
		return generationInput{}, fmt.Errorf("admit executable Artifact set: %w", err)
	}
	if _, err := nexus.CheckRequest(admitted, "umpire.generated.preflight.caller-closure-1"); err != nil {
		return generationInput{}, fmt.Errorf("bind generated test adapter: %w", err)
	}
	executable, ok := admitted.Executable()
	if !ok {
		return generationInput{}, errors.New("generated Go input is not an exact executable set")
	}

	embedRoot, err := filepath.Rel(outputRoot, setRoot)
	if err != nil {
		return generationInput{}, fmt.Errorf("locate generated test fixture: %w", err)
	}
	embedRoot = filepath.ToSlash(filepath.Clean(embedRoot))
	if embedRoot == "." || embedRoot == ".." || strings.HasPrefix(embedRoot, "../") ||
		filepath.IsAbs(embedRoot) {
		return generationInput{}, errors.New("generated test fixture must be below its Go package")
	}
	if err := validateEmbedRoot(embedRoot); err != nil {
		return generationInput{}, err
	}

	experiment := executable.Experiment()
	configuration := executable.RuntimeConfiguration()
	return generationInput{
		packageName: packageName + "_test",
		embedRoot:   embedRoot,
		binding: runner.InputBinding{
			ArtifactSetIdentity:                     admitted.Identity(),
			ArtifactSetChecksum:                     admitted.Checksum(),
			ManifestSHA256:                          admitted.ManifestSHA256(),
			ExperimentArtifactChecksum:              experiment.ArtifactChecksum,
			ExperimentBehaviorFingerprint:           experiment.QueryBehaviorFingerprint,
			RuntimeConfigurationArtifactChecksum:    configuration.ArtifactChecksum,
			RuntimeConfigurationBehaviorFingerprint: configuration.BehaviorFingerprint,
		},
	}, nil
}

func validateEmbedRoot(embedRoot string) error {
	for _, character := range embedRoot {
		switch character {
		case '*', '?', '[', '\\':
			return errors.New("unsafe generated test fixture path contains an embed pattern metacharacter")
		}
		if unicode.IsControl(character) {
			return errors.New("unsafe generated test fixture path contains a control character")
		}
	}
	return nil
}

func readRegularFile(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%q is not a regular file", path)
	}
	return os.ReadFile(path)
}

func renderGeneratedTest(input generationInput) ([]byte, error) {
	var generated strings.Builder
	generated.WriteString("// Code generated by umpire-gen-tests-go. DO NOT EDIT.\n")
	generated.WriteString("// This executes one admitted operational test; semantic Run Evaluation remains separate.\n\n")
	fmt.Fprintf(&generated, "package %s\n\n", input.packageName)
	generated.WriteString("import (\n")
	generated.WriteString("\t\"context\"\n")
	generated.WriteString("\t_ \"embed\"\n")
	generated.WriteString("\t\"testing\"\n")
	generated.WriteString("\t\"time\"\n\n")
	generated.WriteString("\t\"github.com/stretchr/testify/require\"\n")
	generated.WriteString("\t\"go.temporal.io/server/tools/umpire/artifact\"\n")
	generated.WriteString("\t\"go.temporal.io/server/tools/umpire/runner\"\n")
	generated.WriteString("\tumpireruntime \"go.temporal.io/server/tools/umpire/runtime\"\n")
	generated.WriteString("\t\"go.temporal.io/server/tools/umpire/temporal/nexus\"\n")
	generated.WriteString(")\n\n")
	fmt.Fprintf(&generated, "//go:embed %s\n", strconv.Quote(input.embedRoot+"/manifest.json"))
	generated.WriteString("var callerClosureManifest []byte\n\n")
	fmt.Fprintf(&generated, "//go:embed %s\n", strconv.Quote(input.embedRoot+"/artifacts/experiment.json"))
	generated.WriteString("var callerClosureExperiment []byte\n\n")
	fmt.Fprintf(&generated, "//go:embed %s\n", strconv.Quote(input.embedRoot+"/artifacts/runtime-configuration.json"))
	generated.WriteString("var callerClosureRuntimeConfiguration []byte\n\n")
	generated.WriteString("// TestGeneratedWorkflowNexusQueryExactActionCallerClosureExecutesLocally runs the exact\n")
	generated.WriteString("// generated two-member input through the bounded local adapter without publishing it.\n")
	generated.WriteString("func TestGeneratedWorkflowNexusQueryExactActionCallerClosureExecutesLocally(t *testing.T) {\n")
	generated.WriteString("\tinput, err := artifact.AdmitSetFiles(map[string][]byte{\n")
	generated.WriteString("\t\t\"artifacts/experiment.json\":            callerClosureExperiment,\n")
	generated.WriteString("\t\t\"artifacts/runtime-configuration.json\": callerClosureRuntimeConfiguration,\n")
	generated.WriteString("\t\t\"manifest.json\":                        callerClosureManifest,\n")
	generated.WriteString("\t})\n")
	generated.WriteString("\trequire.NoError(t, err)\n\n")
	generated.WriteString("\tctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)\n")
	generated.WriteString("\tdefer cancel()\n")
	generated.WriteString("\toutput, err := runner.Run(\n")
	generated.WriteString("\t\tctx,\n")
	generated.WriteString("\t\tinput,\n")
	generated.WriteString("\t\trunner.InputBinding{\n")
	writeBinding(&generated, input.binding)
	generated.WriteString("\t\t},\n")
	generated.WriteString("\t\t\"umpire.generated.caller-closure.run-1\",\n")
	generated.WriteString("\t\tnexus.Binding{},\n")
	generated.WriteString("\t)\n")
	generated.WriteString("\trequire.NoError(t, err)\n")
	generated.WriteString("\trequire.Equal(t, \"succeeded\", output.ExperimentRun().OperationalStatus)\n")
	generated.WriteString("\trequire.Equal(t, \"closed\", output.RawEvidence().CaptureStatus)\n")
	generated.WriteString("\tsources := output.RawEvidence().Sources\n")
	generated.WriteString("\tsourceDefinitionIDs := make([]string, len(sources))\n")
	generated.WriteString("\tfor index, source := range sources {\n")
	generated.WriteString("\t\tsourceDefinitionIDs[index] = source.SourceDefinitionID\n")
	generated.WriteString("\t}\n")
	generated.WriteString("\trequire.Equal(t, []string{\n")
	generated.WriteString("\t\tumpireruntime.EvidenceSourceCleanup,\n")
	generated.WriteString("\t\tumpireruntime.EvidenceSourceControlReceipt,\n")
	generated.WriteString("\t\tumpireruntime.EvidenceSourceHistory,\n")
	generated.WriteString("\t\tumpireruntime.EvidenceSourceParticipantOutput,\n")
	generated.WriteString("\t}, sourceDefinitionIDs)\n")
	generated.WriteString("\trequire.Empty(t, output.ExperimentRun().KnownGaps)\n")
	generated.WriteString("\trequire.Empty(t, output.RawEvidence().KnownGaps)\n")
	generated.WriteString("}\n")
	formatted, err := format.Source([]byte(generated.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go test: %w", err)
	}
	return formatted, nil
}

func writeBinding(generated *strings.Builder, binding runner.InputBinding) {
	fmt.Fprintf(generated, "\t\t\tArtifactSetIdentity: %q,\n", binding.ArtifactSetIdentity)
	fmt.Fprintf(generated, "\t\t\tArtifactSetChecksum: %q,\n", binding.ArtifactSetChecksum)
	fmt.Fprintf(generated, "\t\t\tManifestSHA256: %q,\n", binding.ManifestSHA256)
	fmt.Fprintf(generated, "\t\t\tExperimentArtifactChecksum: %q,\n", binding.ExperimentArtifactChecksum)
	fmt.Fprintf(generated, "\t\t\tExperimentBehaviorFingerprint: %q,\n", binding.ExperimentBehaviorFingerprint)
	fmt.Fprintf(generated, "\t\t\tRuntimeConfigurationArtifactChecksum: %q,\n", binding.RuntimeConfigurationArtifactChecksum)
	fmt.Fprintf(generated, "\t\t\tRuntimeConfigurationBehaviorFingerprint: %q,\n", binding.RuntimeConfigurationBehaviorFingerprint)
}

func writeGeneratedTest(outputRoot string, generated []byte) error {
	destination := filepath.Join(outputRoot, generatedTestFileName)
	if info, err := os.Lstat(destination); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return errors.New("generated Go destination is not a regular file")
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect generated Go destination: %w", err)
	}
	temporary, err := os.CreateTemp(outputRoot, ".umpire-gen-tests-go-*")
	if err != nil {
		return fmt.Errorf("create generated Go candidate: %w", err)
	}
	temporaryPath := temporary.Name()
	defer func() {
		_ = temporary.Close()
		_ = os.Remove(temporaryPath)
	}()
	if _, err := temporary.Write(generated); err != nil {
		return fmt.Errorf("write generated Go candidate: %w", err)
	}
	if err := temporary.Chmod(0o644); err != nil {
		return fmt.Errorf("set generated Go permissions: %w", err)
	}
	if err := temporary.Sync(); err != nil {
		return fmt.Errorf("sync generated Go candidate: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close generated Go candidate: %w", err)
	}
	if err := os.Rename(temporaryPath, destination); err != nil {
		return fmt.Errorf("publish generated Go test: %w", err)
	}
	return nil
}
