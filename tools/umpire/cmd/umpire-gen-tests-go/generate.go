func run(args []string) error {
	if len(args) != 3 || args[1] != "--output" || args[0] == "" || args[2] == "" {
		return errors.New("expected <manifest> --output <package>")
	}
	input, err := loadGenerationInput(args[0], args[2])
	if err != nil {
		return err
	}
	generated, err := renderGeneratedTest(input)
	if err != nil {
		return err
	}
	return writeGeneratedTest(args[2], generated)
}

func loadGenerationInput(manifestPath, outputRoot string) (generationInput, error) {
	if filepath.Base(manifestPath) != "manifest.json" {
		return generationInput{}, errors.New("generated Go input must be an Artifact set manifest")
	}
	outputInfo, err := os.Lstat(outputRoot)
	if err != nil {
		return generationInput{}, fmt.Errorf("inspect output package: %w", err)
	}
	if outputInfo.Mode()&os.ModeSymlink != 0 || !outputInfo.IsDir() {
		return generationInput{}, errors.New("generated Go output must be a regular package directory")
	}
	packageName := filepath.Base(filepath.Clean(outputRoot))
	if !token.IsIdentifier(packageName) {
		return generationInput{}, errors.New("generated Go output package name is invalid")
	}

	setRoot := filepath.Dir(manifestPath)
	files := make(map[string][]byte, 3)
	for _, relative := range []string{
		"manifest.json",
		"artifacts/experiment.json",
		"artifacts/runtime-configuration.json",
	} {
		encoded, readErr := readRegularFile(filepath.Join(setRoot, filepath.FromSlash(relative)))
		if readErr != nil {
			return generationInput{}, fmt.Errorf("read executable Artifact set: %w", readErr)
		}
		files[relative] = encoded
	}
	admitted, err := artifact.AdmitSetFiles(files)
	if err != nil {
		return generationInput{}, fmt.Errorf("admit executable Artifact set: %w", err)
	}
	request, err := nexus.CheckRequest(admitted, "umpire.generated.preflight.caller-closure-1")
	if err != nil {
		return generationInput{}, fmt.Errorf("bind generated test adapter: %w", err)
	}
	executable, ok := admitted.Executable()
	if !ok {
		return generationInput{}, errors.New("generated Go input is not an exact executable set")
	}

	embedRoot, err := filepath.Rel(outputRoot, setRoot)
	if err != nil {
		return generationInput{}, fmt.Errorf("locate generated test fixture: %w", err)
	}
	embedRoot = filepath.ToSlash(filepath.Clean(embedRoot))
	if embedRoot == "." || embedRoot == ".." || strings.HasPrefix(embedRoot, "../") ||
		filepath.IsAbs(embedRoot) {
		return generationInput{}, errors.New("generated test fixture must be below its Go package")
	}
	if err := validateEmbedRoot(embedRoot); err != nil {
		return generationInput{}, err
	}

	experiment := executable.Experiment()
	configuration := executable.RuntimeConfiguration()
	authority := request.Authority()
	subject, err := runevaluation.PinSubject(files["artifacts/experiment.json"])
	if err != nil {
		return generationInput{}, fmt.Errorf("pin generated Run Evaluation subject: %w", err)
	}
	return generationInput{
		packageName: packageName + "_test",
		embedRoot:   embedRoot,
		subject:     subject,
		binding: runner.InputBinding{
			ArtifactSetIdentity:                      admitted.Identity(),
			ArtifactSetChecksum:                      admitted.Checksum(),
			ManifestSHA256:                           admitted.ManifestSHA256(),
			ExperimentArtifactChecksum:               experiment.ArtifactChecksum,
			ExperimentBehaviorFingerprint:            experiment.QueryBehaviorFingerprint,
			RuntimeConfigurationArtifactChecksum:     configuration.ArtifactChecksum,
			RuntimeConfigurationBehaviorFingerprint:  configuration.BehaviorFingerprint,
			AuthorityRequiredCapabilityDefinitionIDs: authority.RequiredCapabilityDefinitionIDs(),
		},
	}, nil
}

func validateEmbedRoot(embedRoot string) error {
	for _, character := range embedRoot {
		switch character {
		case '*', '?', '[', '\\':
			return errors.New("unsafe generated test fixture path contains an embed pattern metacharacter")
		}
		if unicode.IsControl(character) {
			return errors.New("unsafe generated test fixture path contains a control character")
		}
	}
	return nil
}

func readRegularFile(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%q is not a regular file", path)
	}
	return os.ReadFile(path)
}

