func renderUmbrella(plan leanPlan) []byte {
	var generated strings.Builder
	generated.WriteString("-- Code generated by umpire-gen-api. DO NOT EDIT.\n")
	fmt.Fprintf(&generated, "import %s\n", leanModuleName(plan.TypesModule.Path))
	for _, source := range plan.Sources {
		fmt.Fprintf(&generated, "import %s\n", leanModuleName(source.CatalogModule.Path))
	}
	for _, source := range plan.Sources {
		fmt.Fprintf(&generated, "import %s\n", leanModuleName(source.GRPCModule.Path))
	}
	return []byte(generated.String())
}

func renderTypes(plan leanPlan) []byte {
	var generated strings.Builder
	writeModuleHeader(&generated, plan.TypesModule)
	for _, namespace := range plan.Namespaces {
		fmt.Fprintf(&generated, "namespace %s\n\n", namespace.Name.String())
		for _, enum := range namespace.Enums {
			fmt.Fprintf(&generated, "structure %s where\n  number : Int\n  deriving DecidableEq, Repr\n\n", enum.RelativeName)
			fmt.Fprintf(&generated, "namespace %s\n", enum.RelativeName)
			for _, value := range enum.Values {
				fmt.Fprintf(&generated, "def %s : %s := { number := %d }\n",
					value.Name, enum.RelativeName, value.Projection.Number)
			}
			fmt.Fprintf(&generated, "end %s\n\n", enum.RelativeName)
		}
		for _, message := range namespace.Messages {
			for _, oneof := range message.Oneofs {
				fmt.Fprintf(&generated, "inductive %s where\n  | notSet\n", oneof.RelativeName)
				for _, constructor := range oneof.Constructors {
					fmt.Fprintf(&generated, "  | %s (value : %s)\n",
						constructor.Field.Name, renderLeanType(constructor.Field.BaseType))
				}
				generated.WriteString("  deriving Repr\n\n")
			}
			fmt.Fprintf(&generated, "structure %s where\n", message.RelativeName)
			for _, field := range message.StructureFields {
				fmt.Fprintf(&generated, "  %s : %s\n", field.Name, renderLeanType(field.Type))
			}
			if len(message.StructureFields) == 0 {
				generated.WriteString("  unit : Unit := ()\n")
			}
			generated.WriteString("  deriving Repr\n\n")
		}
		fmt.Fprintf(&generated, "end %s\n\n", namespace.Name.String())
	}
	return []byte(strings.TrimRight(generated.String(), "\n") + "\n")
}

func renderCatalog(source leanSourcePlan, layout outputLayout) []byte {
	var generated strings.Builder
	writeModuleHeader(&generated, source.CatalogModule)
	fmt.Fprintf(&generated, "namespace %s.Proto.Generated.Catalog\n\n", layout.RootModule)
	fmt.Fprintf(&generated, "def %sFiles : List %s.Proto.FileDescriptor := [\n", source.Name, layout.RootModule)
	for _, file := range source.Files {
		fmt.Fprintf(&generated, "  { path := %q, packageName := %q, syntaxName := %q, dependencies := [%s], services := [%s] },\n",
			file.Path, file.Package, file.Syntax, leanStrings(file.Dependencies), leanStrings(file.Services))
	}
	generated.WriteString("]\n\n")
	fmt.Fprintf(&generated, "def %sEnums : List %s.Proto.EnumDescriptor := [\n", source.Name, layout.RootModule)
	for _, enum := range source.Enums {
		fmt.Fprintf(&generated, "  { fullName := %q, values := [", enum.Projection.FullName)
		for index, value := range enum.Values {
			if index > 0 {
				generated.WriteString(", ")
			}
			fmt.Fprintf(&generated, "{ name := %q, number := %d, deprecated := %t }",
				value.Projection.Name, value.Projection.Number, value.Projection.Deprecated)
		}
		fmt.Fprintf(&generated, "], allowAliases := %t, deprecated := %t },\n",
			enum.Projection.AllowAliases, enum.Projection.Deprecated)
	}
	generated.WriteString("]\n\n")
	fmt.Fprintf(&generated, "def %sMessages : List %s.Proto.MessageDescriptor := [\n", source.Name, layout.RootModule)
	for _, message := range source.Messages {
		fmt.Fprintf(&generated, "  { fullName := %q, fields := [\n", message.Projection.FullName)
		for _, field := range message.Fields {
			fmt.Fprintf(&generated, "      { fullName := %q, jsonName := %q, number := %d, kind := %q, typeName := %q, mapKeyType := %q, mapValueType := %q, presence := %t, required := %t, hasDefault := %t, defaultValue := %q, oneofName := %q, repeated := %t, mapField := %t, packed := %t, recursive := %t, deprecated := %t },\n",
				field.Projection.FullName, field.Projection.JSONName, field.Projection.Number, field.Projection.Kind,
				field.Projection.TypeName, field.Projection.MapKey, field.Projection.MapValue,
				field.Projection.Presence, field.Projection.Required, field.Projection.HasDefault,
				field.Projection.Default, field.Projection.Oneof, field.Projection.Repeated,
				field.Projection.Map, field.Projection.Packed, field.Recursive, field.Projection.Deprecated)
		}
		fmt.Fprintf(&generated, "    ], deprecated := %t },\n", message.Projection.Deprecated)
	}
	fmt.Fprintf(&generated, "]\n\nend %s.Proto.Generated.Catalog\n", layout.RootModule)
	return []byte(generated.String())
}

func renderGRPC(source leanSourcePlan, layout outputLayout) []byte {
	var generated strings.Builder
	writeModuleHeader(&generated, source.GRPCModule)
	for _, service := range source.Services {
		fmt.Fprintf(&generated, "namespace %s\n", service.Name.String())
		for _, method := range service.Methods {
			fmt.Fprintf(&generated, "def %s : %s.Proto.Method %s %s :=\n",
				method.Name, layout.RootModule, renderLeanType(method.InputType), renderLeanType(method.OutputType))
			fmt.Fprintf(&generated, "  { fullName := %q, clientStreaming := %t, serverStreaming := %t, deprecated := %t }\n",
				method.Projection.FullName, method.Projection.ClientStreaming,
				method.Projection.ServerStreaming, method.Projection.Deprecated)
		}
		fmt.Fprintf(&generated, "end %s\n\n", service.Name.String())
	}
	fmt.Fprintf(&generated, "namespace %s.Proto.Generated.GRPC\n\n", layout.RootModule)
	fmt.Fprintf(&generated, "def %sServices : List %s.Proto.ServiceDescriptor := [\n", source.Name, layout.RootModule)
	for _, service := range source.Services {
		fmt.Fprintf(&generated, "  { fullName := %q, methods := [\n", service.Projection.FullName)
		for _, method := range service.Methods {
			fmt.Fprintf(&generated, "      { fullName := %q, inputType := %q, outputType := %q, clientStreaming := %t, serverStreaming := %t, deprecated := %t },\n",
				method.Projection.FullName, method.Projection.InputType, method.Projection.OutputType,
				method.Projection.ClientStreaming, method.Projection.ServerStreaming, method.Projection.Deprecated)
		}
		fmt.Fprintf(&generated, "    ], deprecated := %t },\n", service.Projection.Deprecated)
	}
	fmt.Fprintf(&generated, "]\n\nend %s.Proto.Generated.GRPC\n", layout.RootModule)
	return []byte(generated.String())
}

func leanStrings(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = fmt.Sprintf("%q", value)
	}
	return strings.Join(quoted, ", ")
}

func writeGeneratedHeader(generated *strings.Builder) {
	generated.WriteString("-- Code generated by umpire-gen-api. DO NOT EDIT.\n")
	generated.WriteString("-- This is a structural descriptor projection, not behavioral semantics.\n")
}

func writeModuleHeader(generated *strings.Builder, module leanModulePlan) {
	writeGeneratedHeader(generated)
	for _, imported := range module.Imports {
		fmt.Fprintf(generated, "import %s\n", imported)
	}
	generated.WriteString("\nset_option maxRecDepth 100000\n\n")
}

func leanModuleName(path string) string {
	return strings.ReplaceAll(strings.TrimSuffix(path, ".lean"), "/", ".")
}

func canonicalIndentedJSON(value any) ([]byte, error) {
	var encoded bytes.Buffer
	encoder := json.NewEncoder(&encoded)
	encoder.SetIndent("", "  ")
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		return nil, fmt.Errorf("encode generated API artifact: %w", err)
	}
	return encoded.Bytes(), nil
}
