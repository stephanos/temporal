package api

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

const (
	manifestPath = "Temporal/Generated/manifest.json"
	schemaPath   = "Temporal/Generated/schema.json"
)

type artifactDigest struct {
	Path   string `json:"path"`
	Digest string `json:"digest,omitempty"`
}

type generationManifest struct {
	FormatVersion    string            `json:"formatVersion"`
	PublicModule     string            `json:"publicModule"`
	PublicVersion    string            `json:"publicVersion"`
	DescriptorDigest string            `json:"descriptorDigest"`
	Inputs           []descriptorInput `json:"inputs"`
	Files            int               `json:"files"`
	Messages         int               `json:"messages"`
	Enums            int               `json:"enums"`
	Services         int               `json:"services"`
	Methods          int               `json:"methods"`
	GeneratedFiles   []artifactDigest  `json:"generatedFiles"`
}

func generateArtifacts(
	publicModule string,
	publicVersion string,
	inputs []descriptorInput,
	projection projection,
) (map[string][]byte, generationManifest, error) {
	artifacts := map[string][]byte{
		"Temporal/Generated.lean":                  renderUmbrella(),
		"Temporal/Generated/Types.lean":            renderTypes(projection),
		"Temporal/Generated/Catalog/Public.lean":   renderCatalog(projection, sourcePublic),
		"Temporal/Generated/Catalog/Internal.lean": renderCatalog(projection, sourceInternal),
		"Temporal/Generated/Catalog/CHASM.lean":    renderCatalog(projection, sourceCHASM),
		"Temporal/Generated/Catalog/External.lean": renderCatalog(projection, sourceExternal),
		"Temporal/Generated/GRPC/Public.lean":      renderGRPC(projection, sourcePublic),
		"Temporal/Generated/GRPC/Internal.lean":    renderGRPC(projection, sourceInternal),
		"Temporal/Generated/GRPC/CHASM.lean":       renderGRPC(projection, sourceCHASM),
		"Temporal/Generated/GRPC/External.lean":    renderGRPC(projection, sourceExternal),
	}
	schema, err := canonicalIndentedJSON(projection)
	if err != nil {
		return nil, generationManifest{}, err
	}
	artifacts[schemaPath] = schema

	manifest := generationManifest{
		FormatVersion: "umpire/temporal-api/v2", PublicModule: publicModule, PublicVersion: publicVersion,
		DescriptorDigest: projection.DescriptorDigest, Files: len(projection.Files), Messages: len(projection.Messages),
		Enums: len(projection.Enums), Services: len(projection.Services),
	}
	for _, input := range inputs {
		manifest.Inputs = append(manifest.Inputs, descriptorInput{Name: input.Name, Locator: input.Locator, Digest: input.Digest})
	}
	for _, service := range projection.Services {
		manifest.Methods += len(service.Methods)
	}
	paths := make([]string, 0, len(artifacts)+1)
	for path := range artifacts {
		paths = append(paths, path)
	}
	paths = append(paths, manifestPath)
	slices.Sort(paths)
	for _, path := range paths {
		item := artifactDigest{Path: path}
		if encoded, exists := artifacts[path]; exists {
			digest := sha256.Sum256(encoded)
			item.Digest = "sha256:" + hex.EncodeToString(digest[:])
		}
		manifest.GeneratedFiles = append(manifest.GeneratedFiles, item)
	}
	encodedManifest, err := canonicalIndentedJSON(manifest)
	if err != nil {
		return nil, generationManifest{}, err
	}
	artifacts[manifestPath] = encodedManifest
	return artifacts, manifest, nil
}

func renderUmbrella() []byte {
	return []byte(`-- Code generated by umpire-gen-api. DO NOT EDIT.
import Temporal.Generated.Types
import Temporal.Generated.Catalog.Public
import Temporal.Generated.Catalog.Internal
import Temporal.Generated.Catalog.CHASM
import Temporal.Generated.Catalog.External
import Temporal.Generated.GRPC.Public
import Temporal.Generated.GRPC.Internal
import Temporal.Generated.GRPC.CHASM
import Temporal.Generated.GRPC.External
`)
}

func renderTypes(projection projection) []byte {
	var generated strings.Builder
	writeGeneratedHeader(&generated)
	generated.WriteString("import Temporal.Proto.Core\n\nset_option maxRecDepth 100000\n\nnamespace Temporal.Proto.Generated\n\n")
	for _, enum := range projection.Enums {
		fmt.Fprintf(&generated, "structure %s where\n  number : Int\n  deriving DecidableEq, Repr\n\n", enum.LeanName)
		fmt.Fprintf(&generated, "namespace %s\n", enum.LeanName)
		used := make(map[string]int)
		for _, value := range enum.Values {
			name := uniqueName(lowerIdentifier(value.Name), used, value.Number)
			fmt.Fprintf(&generated, "def %s : %s := { number := %d }\n", name, enum.LeanName, value.Number)
		}
		fmt.Fprintf(&generated, "end %s\n\n", enum.LeanName)
	}
	for _, message := range projection.Messages {
		for _, oneof := range message.Oneofs {
			fmt.Fprintf(&generated, "inductive %s where\n  | notSet\n", oneof.LeanName)
			used := map[string]int{"notSet": 1}
			for _, field := range oneof.Fields {
				name := uniqueName(field.LeanName, used, field.Number)
				fmt.Fprintf(&generated, "  | %s (value : %s)\n", name, leanFieldBaseType(field))
			}
			generated.WriteString("  deriving Repr\n\n")
		}
		fmt.Fprintf(&generated, "structure %s where\n", message.LeanName)
		fieldCount := 0
		usedStructureNames := make(map[string]int)
		for _, field := range message.Fields {
			if field.Oneof != "" {
				continue
			}
			fmt.Fprintf(&generated, "  %s : %s\n", field.LeanName, leanFieldType(field))
			usedStructureNames[field.LeanName] = 1
			fieldCount++
		}
		for index, oneof := range message.Oneofs {
			name := uniqueName(lowerIdentifier(oneof.Name), usedStructureNames, int32(index+1))
			fmt.Fprintf(&generated, "  %s : %s\n", name, oneof.LeanName)
			fieldCount++
		}
		if fieldCount == 0 {
			generated.WriteString("  unit : Unit := ()\n")
		}
		generated.WriteString("  deriving Repr\n\n")
	}
	generated.WriteString("end Temporal.Proto.Generated\n")
	return []byte(generated.String())
}

func renderCatalog(projection projection, source sourceKind) []byte {
	var generated strings.Builder
	writeGeneratedHeader(&generated)
	generated.WriteString("import Temporal.Proto.Core\n\nset_option maxRecDepth 100000\n\nnamespace Temporal.Proto.Generated.Catalog\n\n")
	name := upperIdentifier(string(source))
	fmt.Fprintf(&generated, "def %sFiles : List Temporal.Proto.FileDescriptor := [\n", name)
	for _, file := range projection.Files {
		if file.Source != source {
			continue
		}
		fmt.Fprintf(&generated, "  { path := %q, packageName := %q, syntaxName := %q, dependencies := [%s], services := [%s] },\n",
			file.Path, file.Package, file.Syntax, leanStrings(file.Dependencies), leanStrings(file.Services))
	}
	generated.WriteString("]\n\n")
	fmt.Fprintf(&generated, "def %sEnums : List Temporal.Proto.EnumDescriptor := [\n", name)
	for _, enum := range projection.Enums {
		if enum.Source != source {
			continue
		}
		fmt.Fprintf(&generated, "  { fullName := %q, values := [", enum.FullName)
		for index, value := range enum.Values {
			if index > 0 {
				generated.WriteString(", ")
			}
			fmt.Fprintf(&generated, "{ name := %q, number := %d, deprecated := %t }", value.Name, value.Number, value.Deprecated)
		}
		fmt.Fprintf(&generated, "], allowAliases := %t, deprecated := %t },\n", enum.AllowAliases, enum.Deprecated)
	}
	generated.WriteString("]\n\n")
	fmt.Fprintf(&generated, "def %sMessages : List Temporal.Proto.MessageDescriptor := [\n", name)
	for _, message := range projection.Messages {
		if message.Source != source {
			continue
		}
		fmt.Fprintf(&generated, "  { fullName := %q, fields := [\n", message.FullName)
		for _, field := range message.Fields {
			fmt.Fprintf(&generated, "      { fullName := %q, jsonName := %q, number := %d, kind := %q, typeName := %q, mapKeyType := %q, mapValueType := %q, presence := %t, required := %t, hasDefault := %t, defaultValue := %q, oneofName := %q, repeated := %t, mapField := %t, packed := %t, recursive := %t, deprecated := %t },\n",
				field.FullName, field.JSONName, field.Number, field.Kind, field.TypeName, field.MapKey, field.MapValue,
				field.Presence, field.Required, field.HasDefault, field.Default, field.Oneof, field.Repeated, field.Map, field.Packed, field.Recursive, field.Deprecated)
		}
		fmt.Fprintf(&generated, "    ], deprecated := %t },\n", message.Deprecated)
	}
	generated.WriteString("]\n\nend Temporal.Proto.Generated.Catalog\n")
	return []byte(generated.String())
}

func renderGRPC(projection projection, source sourceKind) []byte {
	var generated strings.Builder
	writeGeneratedHeader(&generated)
	generated.WriteString("import Temporal.Proto.Core\nimport Temporal.Generated.Types\n\nset_option maxRecDepth 100000\n\nnamespace Temporal.Proto.Generated.GRPC\n\n")
	name := upperIdentifier(string(source))
	for _, service := range projection.Services {
		if service.Source != source {
			continue
		}
		fmt.Fprintf(&generated, "namespace %s\n", service.LeanName)
		for _, method := range service.Methods {
			fmt.Fprintf(&generated, "def %s : Temporal.Proto.Method %s %s :=\n", method.LeanName, method.InputLeanType, method.OutputLeanType)
			fmt.Fprintf(&generated, "  { fullName := %q, clientStreaming := %t, serverStreaming := %t, deprecated := %t }\n",
				method.FullName, method.ClientStreaming, method.ServerStreaming, method.Deprecated)
		}
		fmt.Fprintf(&generated, "end %s\n\n", service.LeanName)
	}
	fmt.Fprintf(&generated, "def %sServices : List Temporal.Proto.ServiceDescriptor := [\n", name)
	for _, service := range projection.Services {
		if service.Source != source {
			continue
		}
		fmt.Fprintf(&generated, "  { fullName := %q, methods := [\n", service.FullName)
		for _, method := range service.Methods {
			fmt.Fprintf(&generated, "      { fullName := %q, inputType := %q, outputType := %q, clientStreaming := %t, serverStreaming := %t, deprecated := %t },\n",
				method.FullName, method.InputType, method.OutputType, method.ClientStreaming, method.ServerStreaming, method.Deprecated)
		}
		fmt.Fprintf(&generated, "    ], deprecated := %t },\n", service.Deprecated)
	}
	generated.WriteString("]\n\nend Temporal.Proto.Generated.GRPC\n")
	return []byte(generated.String())
}

func leanFieldType(field fieldProjection) string {
	base := leanFieldBaseType(field)
	if field.Map {
		key := leanScalarType(field.MapKey)
		value := leanScalarType(field.MapValue)
		if field.Recursive {
			value = "Temporal.Proto.MessageRef"
		}
		return "List (" + key + " × " + value + ")"
	}
	if field.Repeated {
		return "List " + parenthesize(base)
	}
	if field.Presence && !field.Required {
		return "Option " + parenthesize(base)
	}
	return base
}

func leanFieldBaseType(field fieldProjection) string {
	if field.Recursive {
		return "Temporal.Proto.MessageRef"
	}
	if field.TypeName != "" {
		return leanTypeNameFromString(field.TypeName)
	}
	return leanScalarType(field.Kind)
}

func leanScalarType(kind string) string {
	switch kind {
	case "bool":
		return "Bool"
	case "int32", "sint32", "sfixed32", "int64", "sint64", "sfixed64":
		return "Int"
	case "uint32", "fixed32", "uint64", "fixed64":
		return "Nat"
	case "float", "double":
		return "Float"
	case "string":
		return "String"
	case "bytes":
		return "Temporal.Proto.Bytes"
	default:
		return leanTypeNameFromString(kind)
	}
}

func leanTypeNameFromString(value string) string {
	return leanTypeNameString(value)
}

func leanTypeNameString(value string) string {
	parts := strings.Split(value, ".")
	for index, part := range parts {
		parts[index] = upperIdentifier(part)
	}
	return strings.Join(parts, "_")
}

func parenthesize(value string) string {
	if strings.Contains(value, " ") {
		return "(" + value + ")"
	}
	return value
}

func leanStrings(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = fmt.Sprintf("%q", value)
	}
	return strings.Join(quoted, ", ")
}

func writeGeneratedHeader(generated *strings.Builder) {
	generated.WriteString("-- Code generated by umpire-gen-api. DO NOT EDIT.\n")
	generated.WriteString("-- This is a structural descriptor projection, not behavioral semantics.\n")
}

func canonicalIndentedJSON(value any) ([]byte, error) {
	var encoded bytes.Buffer
	encoder := json.NewEncoder(&encoded)
	encoder.SetIndent("", "  ")
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		return nil, fmt.Errorf("encode generated API artifact: %w", err)
	}
	return encoded.Bytes(), nil
}
