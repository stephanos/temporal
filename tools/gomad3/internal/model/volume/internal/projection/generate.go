const overlay = "internal/backends/native/toolchain/runtime/overlay/src/internal/"

var sources = []struct{ input, output, pkg string }{
	{overlay + "gomadfs/fs.go", "fs_generated.go", "volume"},
	{overlay + "gomadfs/handles.go", "handles_generated.go", "volume"},
	{overlay + "gomadfs/local_handles.go", "local_handles_generated.go", "volume"},
	{overlay + "gomadfs/volume.go", "volume_generated.go", "volume"},
	{overlay + "gomadchoicewire/hash.go", "internal/hashwire/hash_generated.go", "hashwire"},
	{overlay + "gomadchoicewire/wire_generated.go", "internal/hashwire/wire_generated.go", "hashwire"},
}

var processReturns = map[string]string{
	"Resolve":   "return processResolve(name)",
	"Mkdir":     "return processMkdir(name, perm, false)",
	"MkdirAll":  "return processMkdir(name, perm, true)",
	"Stat":      "return processStat(name)",
	"Open":      "return processOpen(name, flags, perm)",
	"Rename":    "return processPathOperation(processVolumeCommand{Operation: processVolumeRenameOp, Path: oldName, Destination: newName})",
	"Remove":    "return processPathOperation(processVolumeCommand{Operation: processVolumeRemoveOp, Path: name})",
	"RemoveAll": "return processPathOperation(processVolumeCommand{Operation: processVolumeRemoveAllOp, Path: name})",
	"Chmod":     "return processPathOperation(processVolumeCommand{Operation: processVolumeChmodOp, Path: name, Mode: mode})",
	"Chtimes":   "return processPathOperation(processVolumeCommand{Operation: processVolumeChtimesOp, Path: name, ModTime: modTime})",
	"Chdir":     "return processPathOperation(processVolumeCommand{Operation: processVolumeChdirOp, Path: name})",
	"Getwd":     "return processGetwd()",
}

type edit struct {
	start, end int
	text       string
}

// Generate projects only the native filesystem's local implementation. Its inputs
// remain owned by the runtime overlay and the existing I/O wire generator.
func Generate(root string) (map[string][]byte, error) {
	outputs := make(map[string][]byte)
	var identities bytes.Buffer
	for _, source := range sources {
		input, err := os.ReadFile(filepath.Join(root, source.input))
		if err != nil {
			return nil, err
		}
		projected, err := rewrite(input, source.pkg, source.output == "fs_generated.go", source.output == "volume_generated.go")
		if err != nil {
			return nil, fmt.Errorf("%s: %w", source.input, err)
		}
		identity := fmt.Sprintf("%x", sha256.Sum256(input))
		fmt.Fprintf(&identities, "%s %s\n", identity, source.input)
		header := fmt.Sprintf("// Code generated by internal/model/volume/cmd/generate. DO NOT EDIT.\n// Source: %s\n// Source SHA256: %s\n\n", source.input, identity)
		outputs[source.output] = append([]byte(header), projected...)
	}
	wire := "internal/model/iowire/wire_generated.go"
	input, err := os.ReadFile(filepath.Join(root, wire))
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&identities, "%x %s\n", sha256.Sum256(input), wire)
	outputs["types_generated.go"], err = mirrorTypes(input, wire)
	if err != nil {
		return nil, err
	}
	// This identity includes the complete shared I/O codec, not only Mount types.
	output := fmt.Sprintf("// Code generated by internal/model/volume/cmd/generate. DO NOT EDIT.\n\npackage volume\n\nconst ProjectionSourcesSHA256 = %q\n\nconst ProjectionSourceInventory = %q\n", fmt.Sprintf("%x", sha256.Sum256(identities.Bytes())), identities.String())
	outputs["provenance_generated.go"], err = format.Source([]byte(output))
	if err != nil {
		return nil, err
	}
	return outputs, nil
}

func rewrite(input []byte, pkg string, stripProcess, adaptObserver bool) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "source.go", input, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	expectedPackage := "gomadfs"
	if pkg == "hashwire" {
		expectedPackage = "gomadchoicewire"
	}
	if file.Name.Name != expectedPackage {
		return nil, fmt.Errorf("source package drift: %s", file.Name.Name)
	}
	edits := []edit{{fset.Position(file.Name.Pos()).Offset, fset.Position(file.Name.End()).Offset, pkg}}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, err
		}
		var replacement string
		switch path {
		case "internal/gomadwire":
			replacement = `gomadwire "go.temporal.io/server/tools/gomad3/internal/model/iowire"`
		case "internal/gomadchoicewire":
			replacement = `gomadchoicewire "go.temporal.io/server/tools/gomad3/internal/model/volume/internal/hashwire"`
		}
		if replacement != "" {
			if spec.Name != nil {
				return nil, fmt.Errorf("unexpected import alias for %s", path)
			}
			edits = append(edits, edit{fset.Position(spec.Pos()).Offset, fset.Position(spec.End()).Offset, replacement})
		}
	}
	if stripProcess {
		branches, err := removeProcessBranches(file, fset)
		if err != nil {
			return nil, err
		}
		edits = append(edits, branches...)
	}
	if stripProcess || adaptObserver {
		adapters, err := ownerAdapters(file, fset, stripProcess)
		if err != nil {
			return nil, err
		}
		edits = append(edits, adapters...)
	}
	sort.Slice(edits, func(i, j int) bool { return edits[i].start > edits[j].start })
	result := append([]byte(nil), input...)
	for _, change := range edits {
		result = append(result[:change.start], append([]byte(change.text), result[change.end:]...)...)
	}
	return format.Source(result)
}

func removeProcessBranches(file *ast.File, fset *token.FileSet) ([]edit, error) {
	guards := 0
	ast.Inspect(file, func(n ast.Node) bool {
		if expression, ok := n.(ast.Expr); ok && processGuard(expression) {
			guards++
		}
		return true
	})
	if guards != 12 {
		return nil, fmt.Errorf("process branch drift: got %d process references, want exactly 12", guards)
	}
	seen := make(map[string]bool)
	var edits []edit
	for _, declaration := range file.Decls {
		fn, ok := declaration.(*ast.FuncDecl)
		if !ok {
			continue
		}
		expected, known := processReturns[fn.Name.Name]
		if !known {
			continue
		}
		if seen[fn.Name.Name] {
			return nil, fmt.Errorf("duplicate process method: %s", fn.Name.Name)
		}
		branch, err := validateProcessBranch(fn, fset, expected)
		if err != nil {
			return nil, err
		}
		seen[fn.Name.Name] = true
		edits = append(edits, edit{fset.Position(branch.Pos()).Offset, fset.Position(branch.End()).Offset, ""})
	}
	if len(seen) != 12 {
		return nil, fmt.Errorf("process branch drift: got %d, want exactly 12", len(seen))
	}
	return edits, nil
}

func validateProcessBranch(fn *ast.FuncDecl, fset *token.FileSet, expected string) (*ast.IfStmt, error) {
	if fn.Recv == nil || fn.Body == nil || len(fn.Body.List) == 0 {
		return nil, fmt.Errorf("process method drift: %s", fn.Name.Name)
	}
	if !filesystemReceiver(fn.Recv) {
		return nil, fmt.Errorf("process receiver drift: %s", fn.Name.Name)
	}
	branch, ok := fn.Body.List[0].(*ast.IfStmt)
	if !ok || !processGuard(branch.Cond) || branch.Init != nil || branch.Else != nil || len(branch.Body.List) != 1 {
		return nil, fmt.Errorf("process branch drift in %s", fn.Name.Name)
	}
	var body bytes.Buffer
	if err := format.Node(&body, fset, branch.Body.List[0]); err != nil {
		return nil, err
	}
	if body.String() != expected {
		return nil, fmt.Errorf("process branch body drift in %s", fn.Name.Name)
	}
	return branch, nil
}

func filesystemReceiver(receiver *ast.FieldList) bool {
	if len(receiver.List) != 1 || len(receiver.List[0].Names) != 1 || receiver.List[0].Names[0].Name != "fs" {
		return false
	}
	pointer, ok := receiver.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	name, ok := pointer.X.(*ast.Ident)
	return ok && name.Name == "FS"
}

func processGuard(expression ast.Expr) bool {
	selector, ok := expression.(*ast.SelectorExpr)
	if !ok || selector.Sel.Name != "process" {
		return false
	}
	receiver, ok := selector.X.(*ast.Ident)
	return ok && receiver.Name == "fs"
}
