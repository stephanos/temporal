type adaptation struct {
	replacement string
	count       int
}

func ownerAdapters(file *ast.File, fset *token.FileSet, filesystem bool) ([]edit, error) {
	rules := map[string]adaptation{
		"type operationObserver interface {\n\tBeforeVolumeOperations(string, []Operation) error\n\tBeforeVolumeControl(string, string, []uint64) error\n}": {"", 1},
		"operationObserver":                {"*Recorder", 2},
		"SetVolumeObserver":                {"SetVolumeRecorder", 1},
		"next.loader = fs.loader":          {"next.loader = fs.loader.clone()", 1},
		"WallNanos":                        {"Work", 1},
		"limits.WallNanos":                 {"limits.Work", 1},
		"CrashCapacityWall":                {"CrashCapacityWork", 1},
		`"wall"`:                           {`"work"`, 1},
		"started := runtimeWallNanotime()": {"budget := enumerationBudget{maximum: limits.Work}", 1},
		"now := runtimeWallNanotime()":     {"", 1},
		"if now >= started && uint64(now-started) >= limits.WallNanos {\n\treturn volume.capacityPage(pendingSHA256, cursor, seenOrder, CrashCapacityWall), nil\n}": {"if !budget.Take() {\npage.Capacity = CrashCapacityWork\npage.ChoiceExploration = newCrashExploration(volumeID, pendingSHA256, cursor, seenOrder)\nreturn page, nil\n}", 1},
	}
	if filesystem {
		rules = map[string]adaptation{
			"type Kind = gomadwire.MountKind":                          {"", 1},
			"type MountStatus = gomadwire.MountStatus":                 {"", 1},
			"type Child = gomadwire.MountChild":                        {"", 1},
			"type LoadEntry = gomadwire.MountEntry":                    {"", 1},
			"type Loader func(string) (LoadEntry, MountStatus, error)": {"", 1},
			"Loader":                         {"*CapturedSnapshot", 2},
			"SetLoader":                      {"SetCapturedSnapshot", 1},
			"fs.loader = loader":             {"fs.loader = loader.clone()", 1},
			"fs.loader(path)":                {"fs.loader.Load(path)", 1},
			"func() int64":                   {"*Clock", 2},
			"fs.clock()":                     {"fs.clock.Now()", 1},
			"gomadwire.MountKindFile":        {"Kind(gomadwire.MountKindFile)", 1},
			"gomadwire.MountKindDirectory":   {"Kind(gomadwire.MountKindDirectory)", 1},
			"gomadwire.MountStatusOK":        {"MountStatus(gomadwire.MountStatusOK)", 1},
			"gomadwire.MountStatusUnmounted": {"MountStatus(gomadwire.MountStatusUnmounted)", 1},
			"gomadwire.MountStatusNotExist":  {"MountStatus(gomadwire.MountStatusNotExist)", 1},
		}
	}
	seen := make(map[string]int)
	declarationTypes := make(map[*ast.FuncType]bool)
	for _, declaration := range file.Decls {
		if fn, ok := declaration.(*ast.FuncDecl); ok {
			declarationTypes[fn.Type] = true
		}
	}
	var edits []edit
	var failure error
	ast.Inspect(file, func(node ast.Node) bool {
		if failure != nil {
			return false
		}
		if fn, ok := node.(*ast.FuncType); ok && declarationTypes[fn] {
			return true
		}
		switch node.(type) {
		case *ast.GenDecl, *ast.Ident, *ast.FuncType, *ast.CallExpr, *ast.SelectorExpr, *ast.AssignStmt, *ast.IfStmt, *ast.BasicLit:
		default:
			return true
		}
		var formatted bytes.Buffer
		if err := format.Node(&formatted, fset, node); err != nil {
			failure = err
			return false
		}
		key := formatted.String()
		rule, exists := rules[key]
		if !exists {
			return true
		}
		seen[key]++
		edits = append(edits, edit{fset.Position(node.Pos()).Offset, fset.Position(node.End()).Offset, rule.replacement})
		return false
	})
	if failure != nil {
		return nil, failure
	}
	for key, rule := range rules {
		if seen[key] != rule.count {
			return nil, fmt.Errorf("typed owner adaptation drift: %s occurrences=%d want=%d", key, seen[key], rule.count)
		}
	}
	return edits, nil
}

func mirrorTypes(input []byte, source string) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, source, input, 0)
	if err != nil {
		return nil, err
	}
	if file.Name.Name != "wire" {
		return nil, fmt.Errorf("authoritative wire package drift: %s", file.Name.Name)
	}
	names := map[string]string{"MountKind": "Kind", "MountStatus": "MountStatus", "MountChild": "Child", "MountEntry": "LoadEntry"}
	declarations := make(map[string]*ast.TypeSpec)
	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok || group.Tok != token.TYPE {
			continue
		}
		for _, spec := range group.Specs {
			typed, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			if _, selected := names[typed.Name.Name]; selected {
				if declarations[typed.Name.Name] != nil {
					return nil, fmt.Errorf("authoritative wire type duplicated: %s", typed.Name.Name)
				}
				declarations[typed.Name.Name] = typed
			}
		}
	}
	var output bytes.Buffer
	fmt.Fprintf(&output, "// Code generated by volume/cmd/generate. DO NOT EDIT.\n// Source: %s\n// Source SHA256: %x\n\npackage volume\n\n", source, sha256.Sum256(input))
	for _, name := range []string{"MountKind", "MountStatus", "MountChild", "MountEntry"} {
		declaration := declarations[name]
		if declaration == nil || declaration.Assign.IsValid() {
			return nil, fmt.Errorf("authoritative wire type drift: %s", name)
		}
		ast.Inspect(declaration, func(node ast.Node) bool {
			if identifier, ok := node.(*ast.Ident); ok {
				if replacement, exists := names[identifier.Name]; exists {
					identifier.Name = replacement
				}
			}
			return true
		})
		output.WriteString("type ")
		if err := format.Node(&output, fset, declaration); err != nil {
			return nil, err
		}
		output.WriteString("\n\n")
	}
	return format.Source(output.Bytes())
}
