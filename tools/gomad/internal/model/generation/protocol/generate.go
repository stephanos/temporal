// Generate renders targets from the schemas under root into outputRoot. Without check it
// writes every output. With check it writes nothing and returns the path of
// every output that is missing or differs. A schema or template error returns
// err.
func Generate(root, outputRoot string, targets []Target, header HeaderFunc, check bool) ([]string, error) {
	inputs := schemaCache{root: root}
	var stale []string
	for _, target := range targets {
		generated, err := inputs.render(target, header)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", target.Path, err)
		}
		destination := filepath.Join(outputRoot, filepath.FromSlash(target.Path))
		if check {
			current, readErr := os.ReadFile(destination)
			if readErr != nil || !bytes.Equal(current, generated) {
				stale = append(stale, target.Path)
			}
			continue
		}
		if err := hostfs.Replace(destination, generated, 0o644); err != nil {
			return nil, fmt.Errorf("write generated %s: %w", target.Path, err)
		}
	}
	return stale, nil
}

// RenderGo renders and formats one Go template outside the target table.
func RenderGo(templatePath string, data any) ([]byte, error) {
	return generate(templatePath, data, "")
}

// schemaCache reads each schema once per Generate call.
type schemaCache struct {
	root    string
	io      *schema
	choice  *choiceTemplateData
	model   *simulationModelSchema
	time    *simulationTimeSchema
	world   *worldSnapshotSchema
	process *processTemplateData
	network *networkWireSchema
	volume  *volumeWireSchema
}

func (cache *schemaCache) path(relative string) string {
	return filepath.Join(cache.root, filepath.FromSlash(relative))
}

func (cache *schemaCache) render(target Target, header HeaderFunc) ([]byte, error) {
	data, err := cache.data(target)
	if err != nil {
		return nil, err
	}
	line := ""
	if header != nil {
		line = header(path.Base(target.Template))
	}
	templatePath := cache.path(target.Template)
	if target.Unformatted {
		return render(templatePath, data, line)
	}
	generated, err := generate(templatePath, data, line)
	if err != nil || !target.Host {
		return generated, err
	}
	return clusterWireSource(generated)
}

func (cache *schemaCache) data(target Target) (any, error) {
	switch target.Family {
	case FamilyIO:
		if cache.io == nil {
			definition, err := readSchema(cache.path("internal/model/schema/iowire.json"))
			if err != nil {
				return nil, err
			}
			cache.io = &definition
		}
		return templateData{Package: target.Package, TestImport: target.TestImport, Schema: *cache.io}, nil
	case FamilyChoice:
		if cache.choice == nil {
			definition, err := readChoiceSchema(cache.path("internal/model/choice/schema/choicewire.json"))
			if err != nil {
				return nil, err
			}
			inputs, err := readChoiceImplementationInputs(cache.root)
			if err != nil {
				return nil, err
			}
			digest := choiceImplementationIdentity(inputs)
			cache.choice = &choiceTemplateData{Schema: definition, ImplementationDigest: string(digest[:])}
		}
		data := *cache.choice
		data.Package, data.TestImport = target.Package, target.TestImport
		return data, nil
	case FamilyModel:
		if cache.model == nil {
			definition, err := readSimulationModelSchema(cache.path("internal/model/schema/modelwire.json"))
			if err != nil {
				return nil, err
			}
			cache.model = &definition
		}
		return simulationModelTemplateData{Package: target.Package, Schema: *cache.model}, nil
	case FamilyTime:
		if cache.time == nil {
			definition, err := readSimulationTimeSchema(cache.path("internal/model/schema/timewire.json"))
			if err != nil {
				return nil, err
			}
			cache.time = &definition
		}
		return simulationTimeTemplateData{Package: target.Package, Schema: *cache.time}, nil
	case FamilyWorld:
		if cache.world == nil {
			definition, err := readWorldSnapshotSchema(cache.path("internal/model/world/schema/snapshotwire.json"))
			if err != nil {
				return nil, err
			}
			cache.world = &definition
		}
		return worldSnapshotTemplateData{Package: target.Package, Schema: *cache.world}, nil
	case FamilyProcess:
		if cache.process == nil {
			definition, err := readProcessSchema(cache.path("internal/model/schema/processwire.json"))
			if err != nil {
				return nil, err
			}
			data, err := processData(definition)
			if err != nil {
				return nil, err
			}
			cache.process = &data
		}
		data := *cache.process
		data.Package = target.Package
		return data, nil
	case FamilyNetwork:
		if cache.network == nil {
			definition, err := readNetworkWireSchema(cache.path("internal/model/schema/networkwire.json"))
			if err != nil {
				return nil, err
			}
			cache.network = &definition
		}
		return networkWireConsumer(target.Host, *cache.network), nil
	case FamilyVolume:
		if cache.volume == nil {
			definition, err := readVolumeWireSchema(cache.path("internal/model/schema/volumewire.json"))
			if err != nil {
				return nil, err
			}
			cache.volume = &definition
		}
		return volumeWireData(*cache.volume, target.Host)
	default:
		return nil, fmt.Errorf("unknown protocol family %d", target.Family)
	}
}
