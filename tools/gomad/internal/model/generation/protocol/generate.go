// Family selects the schema and template data an output is rendered from.
type Family uint8

const (
	FamilyIO Family = iota + 1
	FamilyChoice
	FamilyModel
	FamilyTime
	FamilyWorld
	FamilyProcess
	FamilyNetwork
	FamilyVolume
)

// Target is one generated output. Template and Path are slash-separated and
// relative to the schema root and output root, respectively.
type Target struct {
	Family     Family
	Template   string
	Path       string
	Package    string
	TestImport string
	// Host renders the cluster wire consumer of the process, network and
	// volume codecs: history-owned types and exported names.
	Host bool
	// Unformatted skips gofmt for templates that are not Go.
	Unformatted bool
}

// HeaderFunc returns the first line of an output rendered from the template
// with the given base name. Templates write it as {{header}}.
type HeaderFunc func(template string) string

// SharedHeader is the first line of every output in the shared set.
const SharedHeader = "// Code generated by internal/model/cmd/protocolgen. DO NOT EDIT."

// SharedHeaders is the HeaderFunc of the shared set.
func SharedHeaders(string) string { return SharedHeader }

