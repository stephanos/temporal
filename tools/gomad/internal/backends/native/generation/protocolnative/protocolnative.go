// Headers keeps every native output's generated-file line as it was before
// the generator moved, so native outputs stay byte-identical.
func Headers(template string) string {
	switch template {
	case "networkwire.go.tmpl", "volumewire.go.tmpl":
		return "// Code generated by internal/backends/native/cmd/gomadtool; DO NOT EDIT."
	case "processwire_transport.go.tmpl", "processwire_transport_test.go.tmpl":
		return "// Code generated from simulation/schema/processwire.json by gomadtool protocol-generate; DO NOT EDIT."
	default:
		return "// Code generated by internal/backends/native/cmd/gomadtool protocol-generate. DO NOT EDIT."
	}
}

// Generate writes or checks the native set under the gomad module at root and
// returns the stale outputs. Shared schemas and templates are read from the
// parent module the native go.mod replaces, not from the working directory.
func Generate(root string, check bool) ([]string, error) {
	parent, err := ParentRoot(filepath.Join(root, filepath.FromSlash(nativeRelPath)))
	if err != nil {
		return nil, err
	}
	stale, err := protocol.Generate(parent, Targets(), Headers, check)
	if err != nil {
		return nil, err
	}
	capabilities, err := generateLiveCapabilityProtocols(parent, check)
	if err != nil {
		return nil, err
	}
	return append(stale, capabilities...), nil
}

// ParentRoot resolves the parent gomad module from the replace directive in
// the native module's go.mod at nativeRoot.
func ParentRoot(nativeRoot string) (string, error) {
	path := filepath.Join(nativeRoot, "go.mod")
	contents, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read native module: %w", err)
	}
	file, err := modfile.Parse(path, contents, nil)
	if err != nil {
		return "", fmt.Errorf("parse native module: %w", err)
	}
	if file.Module == nil || file.Module.Mod.Path != nativeModule {
		return "", fmt.Errorf("%s does not declare %s", path, nativeModule)
	}
	for _, replacement := range file.Replace {
		if replacement.Old.Path != parentModule || replacement.New.Version != "" {
			continue
		}
		parent := replacement.New.Path
		if !filepath.IsAbs(parent) {
			parent = filepath.Join(nativeRoot, filepath.FromSlash(parent))
		}
		parentFile, err := os.ReadFile(filepath.Join(parent, "go.mod"))
		if err != nil {
			return "", fmt.Errorf("read parent module: %w", err)
		}
		if modfile.ModulePath(parentFile) != parentModule {
			return "", fmt.Errorf("native replace target %s is not %s", parent, parentModule)
		}
		return filepath.Clean(parent), nil
	}
	return "", errors.New("native module has no directory replace for " + parentModule)
}
