#[test]
fn comments_literals_and_nested_rust_comments() {
    let cases = [
        (
            "\n// comment\nlet a = \"// literal\"; // tail\n/* outer\n/* inner */\nend */ let b = 2;\nlet r = r#\"/* literal\n// still literal\"#;\n",
            "Rust",
            4,
        ),
        ("/* c */\nint x; /* tail */\n", "C", 1),
        ("let x: &'a str; // lifetime\n", "Rust", 1),
        ("let r = r\"\\\"; /* actual comment\nend */\n", "Rust", 1),
        ("let r = br##\"// literal\n/* literal */\"##;\n", "Rust", 2),
    ];
    for (text, lang, expected) in cases {
        assert_eq!(code_lines(text, lang), expected, "{lang}: {text:?}");
    }
}

