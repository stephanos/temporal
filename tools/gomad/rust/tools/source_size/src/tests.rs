#[test]
fn generated_tests_templates_and_subsystems() {
    assert_eq!(category("x_test.go", b"package x"), "tests");
    assert_eq!(category("tests/x.rs", b"// @generated\n"), "generated");
    assert_eq!(
        category("x.rs", b"// Code generated by tool. DO NOT EDIT\n"),
        "generated"
    );
    assert_eq!(category("a/testfixture/x.rs", b""), "tests");
    assert_eq!(language("runtime.go.txt", b""), Some("Go"));
    assert_eq!(language("wire.rs.tmpl", b""), Some("Rust"));
    assert_eq!(language("Makefile", b""), Some("Make"));
    assert_eq!(
        language("script", b"#!/usr/bin/env python3\n"),
        Some("Python")
    );
    for (path, expected) in [
        (
            "tools/gomad/internal/backends/wasm/wasmhost/src/lib.rs",
            "preexisting-rust-helper",
        ),
        ("tools/gomad/rust/wasmhost/src/lib.rs", "linked-rust-engine"),
        (
            "tools/gomad/internal/model/world/world.go",
            "go-model-oracle-toolchain-and-support",
        ),
    ] {
        assert_eq!(subsystem(path), expected);
    }
}

