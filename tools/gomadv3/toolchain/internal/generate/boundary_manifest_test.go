func TestGenerateCompilerTestOverlaySeparatesFixturesFromProduction(t *testing.T) {
	root := t.TempDir()
	writeTestManifest(t, root, validManifest)
	writeCompilerTestManifest(t, root, validCompilerTestManifest)
	if err := Generate(root, false); err != nil {
		t.Fatal(err)
	}
	productionPath := filepath.Join(root, "toolchain", "runtime", "overlay", "src", "cmd", "compile", "internal", "gomadintercept", "spec_go126.go")
	production, err := os.ReadFile(productionPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(production), "example.test/compiler-fixture") {
		t.Fatal("production compiler spec contains a conformance fixture")
	}

	goroot := filepath.Join(root, "goroot")
	installedPath := filepath.Join(goroot, "src", "cmd", "compile", "internal", "gomadintercept", "spec_go126.go")
	if err := os.MkdirAll(filepath.Dir(installedPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(installedPath, production, 0o600); err != nil {
		t.Fatal(err)
	}
	output := filepath.Join(root, "compiler-test-overlay")
	if err := GenerateCompilerTestOverlay(root, goroot, output); err != nil {
		t.Fatal(err)
	}
	testSpec, err := os.ReadFile(filepath.Join(output, "spec_go126.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(testSpec), "example.test/compiler-fixture") {
		t.Fatal("compiler test spec omits the conformance fixture")
	}
	overlay, err := os.ReadFile(filepath.Join(output, "overlay.json"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(overlay), installedPath) || !strings.Contains(string(overlay), filepath.Join(output, "spec_go126.go")) {
		t.Fatalf("compiler test overlay = %s", overlay)
	}
}

