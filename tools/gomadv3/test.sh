require_lifecycle_clean() {
	local debris=
	while IFS= read -r -d '' debris; do break; done < <(find "$lifecycle_toolchain" -mindepth 1 -maxdepth 1 -name 'build.*' -print0)
	if [[ -z "$debris" ]]; then
		while IFS= read -r -d '' debris; do break; done < <(find "$lifecycle_toolchain/locks" -type f -name 'owner.*' -print0)
	fi
	if [[ -z "$debris" ]]; then
		while IFS= read -r -d '' debris; do break; done < <(find "$lifecycle_toolchain/builds" -mindepth 1 -maxdepth 1 -name '*.incomplete.*' -print0)
	fi
	if [[ -z "$debris" ]]; then
		while IFS= read -r -d '' debris; do break; done < <(find "$lifecycle_toolchain/bin" -mindepth 1 -maxdepth 1 -name '*.next.*' -print0)
	fi
	if [[ -z "$debris" ]]; then
		while IFS= read -r -d '' debris; do break; done < <(find "$lifecycle_toolchain" -mindepth 1 -maxdepth 1 -name 'build-key.next.*' -print0)
	fi
	if [[ -n "$debris" ]]; then
		printf 'interrupted builder left temporary state: %s\n' "$debris" >&2
		exit 1
	fi
}

