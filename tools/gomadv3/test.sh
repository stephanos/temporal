start_load_workers() {
	local worker pid
	for worker in 1 2; do
		(while :; do :; done) &
		load_pids+=("$!")
	done
	for pid in "${load_pids[@]}"; do
		if ! kill -0 "$pid" 2>/dev/null; then
			printf 'gomadv3 host-load worker %s failed to start\n' "$pid" >&2
			exit 1
		fi
	done
}

