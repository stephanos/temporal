checked_output() {
	local seconds=$1
	local label=$2
	shift 2
	local result_dir
	result_dir=$(mktemp -d "$test_tmp/process.XXXXXX")
	gomad_run_checked "$seconds" 0 "$label" "$result_dir" "$@"
	if [[ -s "$result_dir/stderr" ]]; then
		while IFS= read -r line || [[ -n "$line" ]]; do
			printf '%s\n' "$line" >&2
		done <"$result_dir/stderr"
	fi
	while IFS= read -r line || [[ -n "$line" ]]; do
		printf '%s\n' "$line"
	done <"$result_dir/stdout"
}

test_builder() {
	unsupported_bootstrap="$test_tmp/unsupported-bootstrap"
	printf '%s\n' \
		'#!/bin/sh' \
		'case "${1:-} ${2:-}" in' \
		'  "env GOROOT") printf "%s\\n" /invalid-bootstrap ;;' \
		'  "env GOHOSTOS") printf "%s\\n" linux ;;' \
		'  "env GOHOSTARCH") printf "%s\\n" amd64 ;;' \
		'  "version ") printf "%s\\n" "go version go1.26.4 linux/amd64" ;;' \
		'  *) exit 2 ;;' \
		'esac' >"$unsupported_bootstrap"
	chmod +x "$unsupported_bootstrap"
	unsupported_platform_result="$test_tmp/unsupported-platform"
	gomad_run_checked 10 1 'builder seed=unset mode=unsupported-platform iteration=0' \
		"$unsupported_platform_result" -- env GOMADV3_BOOTSTRAP_GO="$unsupported_bootstrap" "$script_dir/build.sh"
	if ! grep -Fq 'gomadv3 complete deterministic mode requires host darwin/arm64; got linux/amd64' \
		"$unsupported_platform_result/stdout" "$unsupported_platform_result/stderr"; then
		printf 'gomadv3 builder did not reject an unqualified host before building\n' >&2
		exit 1
	fi

	injection_toolchain="$test_tmp/injection-toolchain"
	injection_result="$test_tmp/injection-after-lock"
	mkdir -p "$injection_toolchain"
	gomad_run_checked 60 86 'builder seed=unset mode=injected-after-lock iteration=0' \
		"$injection_result" -- env GOMADV3_TESTING=1 GOMADV3_TOOLCHAIN_DIR="$injection_toolchain" \
		GOMADV3_TEST_FAIL_PHASE=after-lock "$script_dir/build.sh"

	printf 'not a patch\n' >"$bad_patch"
bad_patch_result="$test_tmp/bad-patch"
gomad_run_checked 60 1 'builder seed=unset mode=invalid-patch iteration=0' "$bad_patch_result" -- \
	env GOMADV3_PATCH_FILE="$bad_patch" "$script_dir/build.sh"
if [[ $(checked_output 10 'go-env seed=unset mode=after-invalid-patch iteration=0' -- \
	"$go_bin" env GOROOT) != "$expected_goroot" ]]; then
	printf 'failed gomadv3 build replaced the stable toolchain\n' >&2
	exit 1
fi

nonapplying_patch="$test_tmp/nonapplying.patch"
printf '%s\n' \
	'diff --git a/src/runtime/proc.go b/src/runtime/proc.go' \
	'--- a/src/runtime/proc.go' \
	'+++ b/src/runtime/proc.go' \
