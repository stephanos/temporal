bad_patch=$(mktemp)
test_tmp=$(mktemp -d)
load_pids=()

stop_load_workers() {
	local failed=false pid
	for pid in "${load_pids[@]}"; do
		if ! kill "$pid" 2>/dev/null; then
			failed=true
		fi
	done
	for pid in "${load_pids[@]}"; do
		wait "$pid" 2>/dev/null || true
	done
	load_pids=()
	[[ "$failed" == false ]]
}

cleanup() {
	local status=$?
	trap - EXIT
	if ((${#load_pids[@]} > 0)) && ! stop_load_workers; then
		printf 'failed to stop gomadv3 host-load workers\n' >&2
		if [[ $status -eq 0 ]]; then
			status=1
		fi
	fi
	rm -f "$bad_patch"
	rm -rf "$test_tmp"
	exit "$status"
}

