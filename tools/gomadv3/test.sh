#!/usr/bin/env bash

set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
go_bin="$script_dir/.toolchain/bin/go"
patch_file=${GOMADV3_PATCH_FILE:-"$script_dir/go1.26.4.patch"}
overlay_dir=${GOMADV3_OVERLAY_DIR:-"$script_dir/overlay"}
testdata_dir="$script_dir/testdata"

sorted_files() {
	local root=$1
	local LC_ALL=C
	local files=() file swap
	local i j
	while IFS= read -r -d '' file; do
		files+=("$file")
	done < <(find "$root" -type f -print0)
	for ((i = 0; i < ${#files[@]}; i++)); do
		for ((j = i + 1; j < ${#files[@]}; j++)); do
			if [[ ${files[j]} < ${files[i]} ]]; then
				swap=${files[i]}
				files[i]=${files[j]}
				files[j]=$swap
			fi
		done
	done
	if ((${#files[@]} > 0)); then
		printf '%s\0' "${files[@]}"
	fi
}

validate_runtime_path() {
	local path=$1
	if [[ "$path" == *$'\n'* ]]; then
		printf 'gomadv3 input path contains a newline\n' >&2
		exit 1
	fi
	case "$path" in
		src/runtime/*.go) ;;
		*)
			printf 'gomadv3 input touches prohibited path: %s\n' "$path" >&2
			exit 1
			;;
	esac
	local name=${path#src/runtime/}
	if [[ "$name" == */* ]]; then
		printf 'gomadv3 input touches prohibited path: %s\n' "$path" >&2
		exit 1
	fi
	case "$name" in
		*_test.go | chan.go | select.go | sema.go | arena.go | heapdump.go | malloc*.go | mbarrier.go | mbitmap.go | mcache.go | mcentral.go | mcheckmark.go | mcleanup.go | mem.go | mem_*.go | mfinal.go | mfixalloc.go | mgc*.go | mheap*.go | mpagealloc*.go | mpagecache*.go | mpallocbits.go | mprof.go | mranges.go | msan*.go | msize.go | mspan*.go | mstats.go | mwbbuf.go | scavenger.go | sizeclasses.go | asan*.go | race*.go | cgo_*.go | defs_*.go | netpoll_*.go | os_*.go | sigqueue_*.go | stubs_*.go | sys_*.go | signal_*.go | vdso_*.go | asm_*.go | rt0_*.go)
			printf 'gomadv3 input touches prohibited runtime area: %s\n' "$path" >&2
			exit 1
			;;
	esac
	if [[ "$name" =~ _32bit\.go$|_64bit\.go$|_386\.go$|_amd64\.go$|_arm\.go$|_arm64\.go$|_loong64\.go$|_mips\.go$|_mips64\.go$|_mips64le\.go$|_mipsle\.go$|_ppc64\.go$|_ppc64le\.go$|_riscv64\.go$|_s390x\.go$|_wasm\.go$|_aix\.go$|_android\.go$|_darwin\.go$|_dragonfly\.go$|_freebsd\.go$|_illumos\.go$|_ios\.go$|_linux\.go$|_netbsd\.go$|_openbsd\.go$|_plan9\.go$|_solaris\.go$|_unix\.go$|_wasip1\.go$|_windows\.go$ ]]; then
		printf 'gomadv3 input touches prohibited platform file: %s\n' "$path" >&2
		exit 1
	fi
}

validate_patch() {
	if [[ ! -s "$patch_file" ]]; then
		printf 'gomadv3 patch is missing: %s\n' "$patch_file" >&2
		exit 1
	fi

	local git_header_count old_header_count new_header_count
	git_header_count=$(awk '$1 == "diff" && $2 == "--git" { count++ } END { print count + 0 }' "$patch_file")
	old_header_count=$(awk '$1 == "---" { count++ } END { print count + 0 }' "$patch_file")
	new_header_count=$(awk '$1 == "+++" { count++ } END { print count + 0 }' "$patch_file")
	if ((git_header_count == 0 || git_header_count != old_header_count || old_header_count != new_header_count)); then
		printf 'gomadv3 patch must contain complete Git file headers\n' >&2
		exit 1
	fi
	if awk '
		$1 == "new" && $2 == "file" && $3 == "mode" { found = 1 }
		($1 == "---" || $1 == "+++") && $2 == "/dev/null" { found = 1 }
		END { exit !found }
	' "$patch_file"; then
		printf 'gomadv3 patch may only modify existing runtime files\n' >&2
		exit 1
	fi

	local path
	while IFS= read -r path; do
		validate_runtime_path "$path"
	done < <(awk '
		$1 == "diff" && $2 == "--git" {
			print substr($3, 3)
			print substr($4, 3)
		}
		($1 == "---" || $1 == "+++") && $2 != "/dev/null" {
			path = $2
			sub(/^[ab]\//, "", path)
			print path
		}
	' "$patch_file" | sort -u)

	if awk '/^GIT binary patch/ || /^Binary files / || /^\+.*Code generated by .* DO NOT EDIT/ { found = 1 } END { exit !found }' "$patch_file"; then
		printf 'gomadv3 patch contains generated or binary output\n' >&2
		exit 1
	fi
}

validate_overlay() {
	if [[ ! -d "$overlay_dir" ]]; then
		printf 'gomadv3 overlay is missing: %s\n' "$overlay_dir" >&2
		exit 1
	fi

	local special=
	while IFS= read -r -d '' special; do
		break
	done < <(find "$overlay_dir" -mindepth 1 ! -type d ! -type f -print0)
	if [[ -n "$special" ]]; then
		printf 'gomadv3 overlay contains a non-regular file: %s\n' "$special" >&2
		exit 1
	fi

	local count=0 file path
	while IFS= read -r -d '' file; do
		count=$((count + 1))
		path=${file#"$overlay_dir"/}
		validate_runtime_path "$path"
		if od -An -tx1 "$file" | awk '{ for (i = 1; i <= NF; i++) if ($i == "00") found = 1 } END { exit !found }'; then
			printf 'gomadv3 overlay contains binary output: %s\n' "$path" >&2
			exit 1
		fi
		if awk '/Code generated by .* DO NOT EDIT/ { found = 1 } END { exit !found }' "$file"; then
			printf 'gomadv3 overlay contains generated output: %s\n' "$path" >&2
			exit 1
		fi
	done < <(sorted_files "$overlay_dir")
	if ((count == 0)); then
		printf 'gomadv3 overlay contains no runtime source files\n' >&2
		exit 1
	fi
}

validate_patch
validate_overlay
if [[ ${1:-} == validate ]]; then
	exit 0
fi

if [[ ! -x "$go_bin" ]]; then
	printf 'gomadv3 toolchain is missing: run make -C %s toolchain\n' "$script_dir" >&2
	exit 1
fi

build_key=$(<"$script_dir/.toolchain/build-key")
expected_goroot="$script_dir/.toolchain/builds/$build_key"
actual_goroot=$("$go_bin" env GOROOT)
if [[ "$actual_goroot" != "$expected_goroot" ]]; then
	printf 'gomadv3 stable path is stale: expected %s, got %s\n' "$expected_goroot" "$actual_goroot" >&2
	exit 1
fi
while IFS= read -r -d '' source; do
	relative=${source#"$overlay_dir"/}
	if ! cmp -s "$source" "$expected_goroot/$relative"; then
		printf 'gomadv3 toolchain does not contain overlay source: %s\n' "$relative" >&2
		exit 1
	fi
done < <(sorted_files "$overlay_dir")

bad_patch=$(mktemp)
test_tmp=$(mktemp -d)
trap 'rm -f "$bad_patch"; rm -rf "$test_tmp"' EXIT
printf 'not a patch\n' >"$bad_patch"
set +e
GOMADV3_PATCH_FILE="$bad_patch" "$script_dir/build.sh" >/dev/null 2>&1
failed_build_status=$?
set -e
if [[ $failed_build_status -eq 0 ]]; then
	printf 'gomadv3 builder accepted an invalid patch\n' >&2
	exit 1
fi
if [[ $("$go_bin" env GOROOT) != "$expected_goroot" ]]; then
	printf 'failed gomadv3 build replaced the stable toolchain\n' >&2
	exit 1
fi

require_rejected_overlay() {
	local overlay=$1
	local reason=$2
	local expected=$3
	local status
	set +e
	GOMADV3_OVERLAY_DIR="$overlay" "$script_dir/build.sh" >"$test_tmp/rejected-overlay.output" 2>&1
	status=$?
	set -e
	if [[ $status -eq 0 ]]; then
		printf 'gomadv3 builder accepted %s overlay\n' "$reason" >&2
		exit 1
	fi
	if ! grep -Fq "$expected" "$test_tmp/rejected-overlay.output"; then
		printf 'gomadv3 builder rejected %s overlay for an unexpected reason:\n' "$reason" >&2
		while IFS= read -r line; do
			printf '%s\n' "$line" >&2
		done <"$test_tmp/rejected-overlay.output"
		exit 1
	fi
	if [[ $("$go_bin" env GOROOT) != "$expected_goroot" ]]; then
		printf 'rejected %s overlay replaced stable toolchain\n' "$reason" >&2
		exit 1
	fi
}

empty_overlay="$test_tmp/empty-overlay"
mkdir -p "$empty_overlay/src/runtime"
require_rejected_overlay "$empty_overlay" empty 'gomadv3 overlay contains no runtime source files'

prohibited_overlay="$test_tmp/prohibited-overlay"
mkdir -p "$prohibited_overlay/src/runtime"
printf 'package runtime\n' >"$prohibited_overlay/src/runtime/chan.go"
require_rejected_overlay "$prohibited_overlay" prohibited 'gomadv3 input touches prohibited runtime area: src/runtime/chan.go'

semaphore_overlay="$test_tmp/semaphore-overlay"
mkdir -p "$semaphore_overlay/src/runtime"
printf 'package runtime\n' >"$semaphore_overlay/src/runtime/sema.go"
require_rejected_overlay "$semaphore_overlay" semaphore 'gomadv3 input touches prohibited runtime area: src/runtime/sema.go'

platform_overlay="$test_tmp/platform-overlay"
mkdir -p "$platform_overlay/src/runtime"
printf 'package runtime\n' >"$platform_overlay/src/runtime/netpoll_epoll.go"
require_rejected_overlay "$platform_overlay" platform 'gomadv3 input touches prohibited runtime area: src/runtime/netpoll_epoll.go'

gc_overlay="$test_tmp/gc-overlay"
mkdir -p "$gc_overlay/src/runtime"
printf 'package runtime\n' >"$gc_overlay/src/runtime/malloc.go"
require_rejected_overlay "$gc_overlay" GC 'gomadv3 input touches prohibited runtime area: src/runtime/malloc.go'

word_size_overlay="$test_tmp/word-size-overlay"
mkdir -p "$word_size_overlay/src/runtime"
printf 'package runtime\n' >"$word_size_overlay/src/runtime/tagptr_64bit.go"
require_rejected_overlay "$word_size_overlay" word-size 'gomadv3 input touches prohibited platform file: src/runtime/tagptr_64bit.go'

newline_overlay="$test_tmp/newline-overlay"
mkdir -p "$newline_overlay/src/runtime"
printf 'package runtime\n' >"$newline_overlay/src/runtime/"$'gomad\nextra.go'
require_rejected_overlay "$newline_overlay" newline 'gomadv3 input path contains a newline'

symlink_overlay="$test_tmp/symlink-overlay"
mkdir -p "$symlink_overlay/src/runtime"
ln -s "$patch_file" "$symlink_overlay/src/runtime/gomad.go"
require_rejected_overlay "$symlink_overlay" symlink 'gomadv3 overlay contains a non-regular file:'

collision_overlay="$test_tmp/collision-overlay"
mkdir -p "$collision_overlay/src/runtime"
printf 'package runtime\n' >"$collision_overlay/src/runtime/proc.go"
require_rejected_overlay "$collision_overlay" colliding 'gomadv3 overlay collides with upstream Go source: src/runtime/proc.go'

stale_lock="$script_dir/.toolchain/locks/$build_key"
mkdir "$stale_lock"
printf '999999\n' >"$stale_lock/owner.stale-test"

"$script_dir/build.sh" >"$test_tmp/build.first" &
first_build=$!
"$script_dir/build.sh" >"$test_tmp/build.second" &
second_build=$!
set +e
wait "$first_build"
first_build_status=$?
wait "$second_build"
second_build_status=$?
set -e
if [[ $first_build_status -ne 0 || $second_build_status -ne 0 ]]; then
	printf 'concurrent gomadv3 cached builds failed: %d, %d\n' "$first_build_status" "$second_build_status" >&2
	exit 1
fi
if [[ $("$go_bin" env GOROOT) != "$expected_goroot" ]]; then
	printf 'concurrent gomadv3 builds replaced the stable toolchain\n' >&2
	exit 1
fi

prohibited_patch="$test_tmp/prohibited.patch"
printf '%s\n' \
	'--- src/runtime/chan.go' \
	'+++ src/runtime/chan.go' \
	'@@ -1 +1 @@' \
	'-package runtime' \
	'+package runtime' >"$prohibited_patch"
if GOMADV3_PATCH_FILE="$prohibited_patch" "$script_dir/test.sh" validate >/dev/null 2>&1; then
	printf 'gomadv3 patch validation accepted a headerless prohibited patch\n' >&2
	exit 1
fi

new_file_patch="$test_tmp/new-file.patch"
printf '%s\n' \
	'diff --git a/src/runtime/extra.go b/src/runtime/extra.go' \
	'new file mode 100644' \
	'--- /dev/null' \
	'+++ b/src/runtime/extra.go' \
	'@@ -0,0 +1 @@' \
	'+package runtime' >"$new_file_patch"
if GOMADV3_PATCH_FILE="$new_file_patch" "$script_dir/test.sh" validate >/dev/null 2>&1; then
	printf 'gomadv3 patch validation accepted a new runtime file\n' >&2
	exit 1
fi

run_enabled() {
	local seed=$1
	local package=$2
	env GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED="$seed" \
		"$go_bin" -C "$testdata_dir" run "$package"
}

require_repeatable() {
	local package=$1
	local seed=$2
	local runs=${3:-100}
	local expected
	expected=$(run_enabled "$seed" "$package")
	for ((run = 1; run < runs; run++)); do
		local actual
		actual=$(run_enabled "$seed" "$package")
		if [[ "$actual" != "$expected" ]]; then
			printf 'same-seed output diverged for %s seed %s on run %d\n' "$package" "$seed" "$run" >&2
			diff -u <(printf '%s\n' "$expected") <(printf '%s\n' "$actual") || true
			exit 1
		fi
	done
}

require_diverse() {
	local package=$1
	local outputs
	outputs=$(mktemp)
	trap 'rm -f "$outputs"' RETURN
	for seed in {0..31}; do
		run_enabled "$seed" "$package" | shasum -a 256 >>"$outputs"
	done
	if [[ $(sort -u "$outputs" | wc -l) -le 1 ]]; then
		printf 'different seeds produced no diversity for %s\n' "$package" >&2
		exit 1
	fi
}

require_invalid_seed() {
	local seed=$1
	local output
	local status
	set +e
	output=$(env GOMADSEED="$seed" "$go_bin" -C "$testdata_dir" run ./activation 2>&1)
	status=$?
	set -e
	if [[ $status -eq 0 || "$output" != *"invalid GOMADSEED"* ]]; then
		printf 'expected GOMADSEED=%q to fail before init, status=%d output=%s\n' "$seed" "$status" "$output" >&2
		exit 1
	fi
}

run_with_timeout() {
	local seconds=$1
	shift
	perl -e '
		my $seconds = shift @ARGV;
		my $pid = fork();
		die "fork failed: $!\n" unless defined $pid;
		if ($pid == 0) {
			exec @ARGV;
			exit 127;
		}
		$SIG{ALRM} = sub {
			kill 9, $pid;
			waitpid $pid, 0;
			exit 124;
		};
		alarm $seconds;
		waitpid $pid, 0;
		my $status = $?;
		alarm 0;
		exit(($status & 127) ? 128 + ($status & 127) : $status >> 8);
	' "$seconds" "$@"
}

disabled_output=$(env -u GOMADSEED GOMAXPROCS=2 "$go_bin" -C "$testdata_dir" run ./activation)
[[ "$disabled_output" == $'init GOMAXPROCS=2\nmain GOMAXPROCS=2' ]]

for seed in 0 1 18446744073709551615; do
	enabled_output=$(env GODEBUG= GOMAXPROCS=8 GOMADSEED="$seed" "$go_bin" -C "$testdata_dir" run ./activation)
	[[ "$enabled_output" == $'init GOMAXPROCS=1\nmain GOMAXPROCS=1' ]]
done

require_invalid_seed ""
require_invalid_seed invalid
require_invalid_seed 18446744073709551616

expected_random=$'0a7525e1e05ff5fe ffb8ed0e\n122dfc0fe2d508a6 1b002cf4\nd12bfa4e65a4f412 2bddb89d\ne130e2e2979e3a1e 24a3f658\nd7e2a1a8cc5a63ee b168521b\n477215d4f3636667 9d887e07\n20b3cd5be81d313a f76e0a45\n1520901c1d837c7b d6ac53c6'
actual_random=$(run_enabled 1 ./random)
if [[ "$actual_random" != "$expected_random" ]]; then
	printf 'seed 1 runtime random sequence changed\n' >&2
	diff -u <(printf '%s\n' "$expected_random") <(printf '%s\n' "$actual_random") || true
	exit 1
fi

for package in ./random ./scheduler_min ./scheduler ./select ./maps ./channels ./sync; do
	require_repeatable "$package" 1
done

for package in ./scheduler ./select ./channels ./sync; do
	require_diverse "$package"
done

scheduler_bin="$test_tmp/scheduler"
env -u GOMADSEED "$go_bin" -C "$testdata_dir" build -o "$scheduler_bin" ./scheduler
expected_direct=$(env GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 "$scheduler_bin")
for ((run = 1; run < 100; run++)); do
	actual_direct=$(env GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 "$scheduler_bin")
	[[ "$actual_direct" == "$expected_direct" ]]
done

parallel_dir="$test_tmp/parallel"
mkdir -p "$parallel_dir"
for seed in 3 7 11 19; do
	run_enabled "$seed" ./scheduler >"$parallel_dir/$seed.first" &
	run_enabled "$seed" ./scheduler >"$parallel_dir/$seed.second" &
done
wait
for seed in 3 7 11 19; do
	cmp "$parallel_dir/$seed.first" "$parallel_dir/$seed.second"
done

cold_cache="$test_tmp/go-cache"
mkdir -p "$cold_cache"
cold_output=$(env GOCACHE="$cold_cache" GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 \
	"$go_bin" -C "$testdata_dir" run ./scheduler)
warm_output=$(env GOCACHE="$cold_cache" GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 \
	"$go_bin" -C "$testdata_dir" run ./scheduler)
[[ "$cold_output" == "$warm_output" ]]

disabled_maps="$test_tmp/disabled-maps"
for run in {1..16}; do
	env -u GOMADSEED "$go_bin" -C "$testdata_dir" run ./maps | shasum -a 256 >>"$disabled_maps"
done
if [[ $(sort -u "$disabled_maps" | wc -l) -le 1 ]]; then
	printf 'disabled gomadv3 unexpectedly fixed map iteration order\n' >&2
	exit 1
fi

preemption_bin="$test_tmp/preemption"
env -u GOMADSEED "$go_bin" -C "$testdata_dir" build -o "$preemption_bin" ./preemption
disabled_preemption=$(run_with_timeout 5 env -u GOMADSEED GOMAXPROCS=1 "$preemption_bin")
[[ "$disabled_preemption" == "async preemption enabled" ]]
set +e
run_with_timeout 2 env GODEBUG= GOMAXPROCS=1 GOMADSEED=1 "$preemption_bin" >/dev/null 2>&1
enabled_preemption_status=$?
set -e
if [[ $enabled_preemption_status -ne 124 ]]; then
	printf 'gomadv3 deterministic preemption watchdog returned status %d, want 124\n' "$enabled_preemption_status" >&2
	exit 1
fi

expected_test=$(env GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 \
	"$go_bin" -C "$testdata_dir" test -count=1 -tags=test_dep -v ./gotest)
for ((run = 1; run < 100; run++)); do
	actual_test=$(env GODEBUG=asyncpreemptoff=1 GOMAXPROCS=1 GOMADSEED=1 \
		"$go_bin" -C "$testdata_dir" test -count=1 -tags=test_dep -v ./gotest)
	[[ "$actual_test" == "$expected_test" ]]
done

upstream_goroot="$test_tmp/upstream-go"
ln -s "$actual_goroot" "$upstream_goroot"
env -u GOMADSEED -u GO111MODULE -u GODEBUG -u GOWORK \
	"$upstream_goroot/bin/go" -C "$upstream_goroot/src" test -tags=test_dep runtime

printf 'gomadv3 black-box tests passed\n'
