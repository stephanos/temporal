			printf 'seed %s runtime random output is malformed: %q\n' "$seed" "$line" >&2
			exit 1
		fi
	done <<<"$output"
	if ((line_count != 8)); then
		printf 'seed %s runtime random output has %d lines, expected 8\n' "$seed" "$line_count" >&2
		exit 1
	fi
}

