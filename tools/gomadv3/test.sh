checked_output() {
	local seconds=$1
	local label=$2
	shift 2
	local result_dir
	result_dir=$(mktemp -d "$test_tmp/process.XXXXXX")
	gomad_run_checked "$seconds" 0 "$label" "$result_dir" "$@"
	if [[ -s "$result_dir/stderr" ]]; then
		while IFS= read -r line || [[ -n "$line" ]]; do
			printf '%s\n' "$line" >&2
		done <"$result_dir/stderr"
	fi
	while IFS= read -r line || [[ -n "$line" ]]; do
		printf '%s\n' "$line"
	done <"$result_dir/stdout"
}

