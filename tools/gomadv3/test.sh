gomad_run_checked 60 1 'builder seed=unset mode=toolchain-failure iteration=0' "$failing_build_result" -- \
	env GOMADV3_PATCH_FILE="$nonapplying_patch" "$script_dir/build.sh"
if ! grep -Eq 'gomadv3 toolchain build failed \(key [0-9a-f]{64}\)' \
	"$failing_build_result/stdout" "$failing_build_result/stderr"; then
	printf 'gomadv3 toolchain failure omitted its immutable build key\n' >&2
	exit 1
fi
if [[ $(checked_output 10 'go-env seed=unset mode=after-toolchain-failure iteration=0' -- \
	"$go_bin" env GOROOT) != "$expected_goroot" ]]; then
	printf 'failed gomadv3 toolchain build replaced the stable toolchain\n' >&2
	exit 1
fi

require_rejected_overlay() {
	local overlay=$1
	local reason=$2
	local expected=$3
	local result_dir="$test_tmp/rejected-overlay-$reason"
	gomad_run_checked 60 1 "builder seed=unset mode=rejected-$reason-overlay iteration=0" "$result_dir" -- \
		env GOMADV3_OVERLAY_DIR="$overlay" "$script_dir/build.sh"
	if ! grep -Fq "$expected" "$result_dir/stdout" "$result_dir/stderr"; then
		printf 'gomadv3 builder rejected %s overlay for an unexpected reason:\n' "$reason" >&2
		while IFS= read -r line; do
			printf '%s\n' "$line" >&2
		done <"$result_dir/stderr"
		exit 1
	fi
	if [[ $(checked_output 10 "go-env seed=unset mode=after-rejected-$reason-overlay iteration=0" -- \
		"$go_bin" env GOROOT) != "$expected_goroot" ]]; then
		printf 'rejected %s overlay replaced stable toolchain\n' "$reason" >&2
		exit 1
	fi
}

