run_hosttool() {
	local host_go=${GOMADV3_BOOTSTRAP_GO:-}
	if [[ -z $host_go ]]; then
		host_go=$(command -v go || true)
	fi
	if [[ -z $host_go || ! -x $host_go ]]; then
		printf 'gomadv3 requires an installed bootstrap Go; set GOMADV3_BOOTSTRAP_GO\n' >&2
		return 1
	fi
	env -u GOMADSEED GOCACHE="$script_dir/.toolchain/generator-cache" GOTOOLCHAIN=local GOWORK=off \
		"$host_go" -C "$script_dir" run ./internal/hosttool "$@"
}

