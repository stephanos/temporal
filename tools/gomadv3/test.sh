	make --no-print-directory -C "$repo_root" gomadv3-test GOMADSEED=101 \
	GOMADV3_PACKAGES=./tools/gomadv3roottestdata/tagged GOMADV3_ARGS=-run=TestTargetRequiresTestDep)
