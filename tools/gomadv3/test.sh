require_stock_compatibility() {
	local stock_go=${GOMADV3_STOCK_GO:-}
	if [[ -z "$stock_go" ]]; then
		local stock_launcher stock_root
		stock_launcher=$(command -v go || true)
		if [[ -n "$stock_launcher" ]]; then
			if stock_root=$(checked_output 10 'stock-go seed=unset mode=resolve iteration=0' -- \
				env -u GOMADSEED GONOSUMDB='*' GOPROXY=off \
				"$stock_launcher" -C "$testdata_dir" env GOROOT 2>/dev/null); then
				stock_go="$stock_root/bin/go"
			fi
		fi
	fi
	if [[ -z "$stock_go" || ! -x "$stock_go" ]]; then
		printf 'stock Go is missing; set GOMADV3_STOCK_GO to a %s executable\n' "$go_version" >&2
		exit 1
	fi

	local stock_version stock_root
	stock_version=$(checked_output 10 'stock-go seed=unset mode=version iteration=0' -- \
		env -u GOMADSEED GOTOOLCHAIN=local "$stock_go" version)
	stock_root=$(checked_output 10 'stock-go seed=unset mode=goroot iteration=0' -- \
		env -u GOMADSEED GOTOOLCHAIN=local "$stock_go" env GOROOT)
	if [[ "$stock_version" != "go version $go_version "* ]]; then
		printf 'stock Go must report %s; %s reported: %s\n' "$go_version" "$stock_go" "$stock_version" >&2
		exit 1
	fi
	if [[ ! -d "$stock_root" ]]; then
		printf 'stock Go reported an invalid GOROOT: %s\n' "$stock_root" >&2
		exit 1
	fi
	local canonical_stock_root canonical_custom_root
	canonical_stock_root=$(cd "$stock_root" && pwd -P)
	canonical_custom_root=$(cd "$actual_goroot" && pwd -P)
	if [[ "$canonical_stock_root" == "$canonical_custom_root" ]]; then
		printf 'stock Go resolves to the gomadv3 custom GOROOT: %s\n' "$canonical_stock_root" >&2
		exit 1
	fi

	local custom_output stock_output
	custom_output=$(checked_output 60 'activation seed=unset mode=custom-compatibility iteration=0' -- \
		env -u GOMADSEED GODEBUG= GOMAXPROCS=2 GOTOOLCHAIN=local GOWORK=off \
		"$go_bin" -C "$testdata_dir" run ./activation)
	stock_output=$(checked_output 60 'activation seed=unset mode=stock-compatibility iteration=0' -- \
		env -u GOMADSEED GODEBUG= GOMAXPROCS=2 GOTOOLCHAIN=local GOWORK=off \
		"$stock_go" -C "$testdata_dir" run ./activation)
	if [[ "$custom_output" != "$stock_output" ]]; then
		printf 'disabled go run output differs from stock %s\n' "$go_version" >&2
		diff -u <(printf '%s\n' "$stock_output") <(printf '%s\n' "$custom_output") || true
		exit 1
	fi

	local custom_test stock_test
	custom_test=$(checked_output 60 'gotest seed=unset mode=custom-compatibility iteration=0' -- \
		env -u GOMADSEED GODEBUG= GOMAXPROCS=2 GOTOOLCHAIN=local GOWORK=off \
		"$go_bin" -C "$testdata_dir" test -count=1 -tags=test_dep -run '^TestDisabledCompatibility$' -v ./gotest)
	stock_test=$(checked_output 60 'gotest seed=unset mode=stock-compatibility iteration=0' -- \
		env -u GOMADSEED GODEBUG= GOMAXPROCS=2 GOTOOLCHAIN=local GOWORK=off \
		"$stock_go" -C "$testdata_dir" test -count=1 -tags=test_dep -run '^TestDisabledCompatibility$' -v ./gotest)

	local custom_line stock_line
	custom_line=$(grep '^GOMADV3_COMPAT ' <<<"$custom_test" || true)
	stock_line=$(grep '^GOMADV3_COMPAT ' <<<"$stock_test" || true)
	if [[ -z "$custom_line" || -z "$stock_line" ]]; then
		printf 'disabled go test compatibility output is missing: custom=%q stock=%q\n' "$custom_line" "$stock_line" >&2
		exit 1
	fi
	if [[ $(grep -c '^GOMADV3_COMPAT ' <<<"$custom_test") -ne 1 || $(grep -c '^GOMADV3_COMPAT ' <<<"$stock_test") -ne 1 ]]; then
		printf 'disabled go test compatibility output must appear exactly once\n' >&2
		exit 1
	fi
	if [[ "$custom_line" != "$stock_line" ]]; then
		printf 'disabled go test output differs from stock %s\n' "$go_version" >&2
		diff -u <(printf '%s\n' "$stock_line") <(printf '%s\n' "$custom_line") || true
		exit 1
	fi

	local custom_benchmark stock_benchmark custom_ns stock_ns
	custom_benchmark=$(run_disabled_clock_benchmark "$go_bin" custom 0)
	stock_benchmark=$(run_disabled_clock_benchmark "$stock_go" stock 0)
	stock_benchmark+=$'\n'$(run_disabled_clock_benchmark "$stock_go" stock 1)
	custom_benchmark+=$'\n'$(run_disabled_clock_benchmark "$go_bin" custom 1)
	custom_ns=$(benchmark_median_ns <<<"$custom_benchmark")
	stock_ns=$(benchmark_median_ns <<<"$stock_benchmark")
	if ! awk -v custom="$custom_ns" -v stock="$stock_ns" 'BEGIN {
		limit = stock * 2
		if (limit < stock + 10) limit = stock + 10
		exit !(custom <= limit)
	}'; then
		printf 'disabled clock read regression: custom median %s ns/op, stock median %s ns/op\n' \
			"$custom_ns" "$stock_ns" >&2
		exit 1
	fi
}

require_address_perturbation() {
	local package=$1
	local addresses="$test_tmp/address-layout-${package#./}"
	local expected_payload=
	local padding output marker marker_line payload
	for padding in 0 1048576 4194304; do
		output=$(checked_output 60 "$package seed=1 mode=address-padding iteration=$padding" -- \
			env -u GOMADSEED CGO_ENABLED=0 GOGC=off TZ=UTC GOMADV3_ADDRESS_PADDING="$padding" \
			GOMADV3_CHILD_SEED=1 "$go_bin" -C "$testdata_dir" run -exec "$exec_wrapper" "$package")
		marker_line=$(grep '^GOMADV3_ADDRESS ' <<<"$output" || true)
		if [[ $(grep -c '^GOMADV3_ADDRESS ' <<<"$output") -ne 1 ]]; then
			printf '%s address perturbation emitted no unique marker for padding %s\n' "$package" "$padding" >&2
			exit 1
		fi
		if [[ "${output##*$'\n'}" != "$marker_line" ]]; then
			printf '%s address perturbation emitted its marker before completing output for padding %s\n' "$package" "$padding" >&2
			exit 1
		fi
		marker=$marker_line
		marker=${marker#GOMADV3_ADDRESS }
		if [[ ! "$marker" =~ ^0x[0-9a-f]+$ ]]; then
			printf '%s address perturbation emitted invalid marker for padding %s: %s\n' "$package" "$padding" "$marker" >&2
			exit 1
		fi
		printf '%s\n' "$marker" >>"$addresses"
		payload=$(sed '/^GOMADV3_ADDRESS /d' <<<"$output")
		if [[ -z "$expected_payload" ]]; then
			expected_payload=$payload
		elif [[ "$payload" != "$expected_payload" ]]; then
			printf '%s output changed under address perturbation for padding %s\n' "$package" "$padding" >&2
			diff -u <(printf '%s\n' "$expected_payload") <(printf '%s\n' "$payload") || true
			exit 1
		fi
	done
	if [[ $(sort -u "$addresses" | wc -l) -le 1 ]]; then
		printf '%s address perturbation did not produce distinct layouts\n' "$package" >&2
		exit 1
	fi
}

