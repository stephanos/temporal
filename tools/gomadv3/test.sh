require_host_load() {
	local labels=() binaries=() expected=()
	local actual index run pid
	while (($# > 0)); do
		labels+=("$1")
		binaries+=("$2")
		shift 2
	done
	for index in "${!labels[@]}"; do
		expected+=("$(run_host_fixture "${labels[index]} baseline" "${binaries[index]}")")
	done
	start_load_workers
	for run in {1..8}; do
		for index in "${!labels[@]}"; do
			actual=$(run_host_fixture "${labels[index]} host-load run $run" "${binaries[index]}")
			if [[ "$actual" != "${expected[index]}" ]]; then
				printf '%s output changed under unrelated host CPU load on run %d\n' "${labels[index]}" "$run" >&2
				diff -u <(printf '%s\n' "${expected[index]}") <(printf '%s\n' "$actual") || true
				exit 1
			fi
		done
	done
	for pid in "${load_pids[@]}"; do
		if ! kill -0 "$pid" 2>/dev/null; then
			printf 'gomadv3 host-load worker %s exited early\n' "$pid" >&2
			exit 1
