sorted_files() {
	local root=$1
	local LC_ALL=C
	local files=() file swap
	local i j
	while IFS= read -r -d '' file; do
		files+=("$file")
	done < <(find "$root" -type f -print0)
	for ((i = 0; i < ${#files[@]}; i++)); do
		for ((j = i + 1; j < ${#files[@]}; j++)); do
			if [[ ${files[j]} < ${files[i]} ]]; then
				swap=${files[i]}
				files[i]=${files[j]}
				files[j]=$swap
			fi
		done
	done
	if ((${#files[@]} > 0)); then
		printf '%s\0' "${files[@]}"
	fi
}

validate_runtime_path() {
	local path=$1
	if [[ "$path" == *$'\n'* ]]; then
		printf 'gomadv3 input path contains a newline\n' >&2
		exit 1
	fi
	case "$path" in
		src/runtime/*.go) ;;
		*)
			printf 'gomadv3 input touches prohibited path: %s\n' "$path" >&2
			exit 1
			;;
	esac
	local name=${path#src/runtime/}
	if [[ "$name" == */* ]]; then
		printf 'gomadv3 input touches prohibited path: %s\n' "$path" >&2
		exit 1
	fi
	case "$name" in
		*_test.go | chan.go | select.go | sema.go | arena.go | heapdump.go | malloc*.go | mbarrier.go | mbitmap.go | mcache.go | mcentral.go | mcheckmark.go | mcleanup.go | mem.go | mem_*.go | mfinal.go | mfixalloc.go | mgc*.go | mheap*.go | mpagealloc*.go | mpagecache*.go | mpallocbits.go | mprof.go | mranges.go | msan*.go | msize.go | mspan*.go | mstats.go | mwbbuf.go | scavenger.go | sizeclasses.go | asan*.go | race*.go | cgo_*.go | defs_*.go | netpoll_*.go | os_*.go | sigqueue_*.go | stubs_*.go | sys_*.go | signal_*.go | vdso_*.go | asm_*.go | rt0_*.go)
			printf 'gomadv3 input touches prohibited runtime area: %s\n' "$path" >&2
			exit 1
			;;
	esac
	if [[ "$name" =~ _32bit\.go$|_64bit\.go$|_386\.go$|_amd64\.go$|_arm\.go$|_arm64\.go$|_loong64\.go$|_mips\.go$|_mips64\.go$|_mips64le\.go$|_mipsle\.go$|_ppc64\.go$|_ppc64le\.go$|_riscv64\.go$|_s390x\.go$|_wasm\.go$|_aix\.go$|_android\.go$|_darwin\.go$|_dragonfly\.go$|_freebsd\.go$|_illumos\.go$|_ios\.go$|_linux\.go$|_netbsd\.go$|_openbsd\.go$|_plan9\.go$|_solaris\.go$|_unix\.go$|_wasip1\.go$|_windows\.go$ ]]; then
		printf 'gomadv3 input touches prohibited platform file: %s\n' "$path" >&2
		exit 1
	fi
}

validate_patch_path() {
	local allowed
	for allowed in "${patch_allowed_paths[@]}"; do
		if [[ $1 == "$allowed" ]]; then
			return
		fi
	done
	validate_runtime_path "$1"
	printf 'gomadv3 input touches prohibited path: %s\n' "$1" >&2
	exit 1
}

validate_patch() {
	if [[ ! -s "$patch_file" ]]; then
		printf 'gomadv3 patch is missing: %s\n' "$patch_file" >&2
		exit 1
	fi
	if ! git apply --numstat <"$patch_file" >/dev/null 2>&1; then
		printf 'gomadv3 patch is malformed\n' >&2
		exit 1
	fi

	local git_header_count old_header_count new_header_count
	git_header_count=$(awk '$1 == "diff" && $2 == "--git" { count++ } END { print count + 0 }' "$patch_file")
	old_header_count=$(awk '$1 == "---" { count++ } END { print count + 0 }' "$patch_file")
	new_header_count=$(awk '$1 == "+++" { count++ } END { print count + 0 }' "$patch_file")
	if ((git_header_count == 0 || git_header_count != old_header_count || old_header_count != new_header_count)); then
		printf 'gomadv3 patch must contain complete Git file headers\n' >&2
		exit 1
	fi
	if awk '
		$1 == "new" && $2 == "file" && $3 == "mode" { found = 1 }
		($1 == "---" || $1 == "+++") && $2 == "/dev/null" { found = 1 }
		END { exit !found }
	' "$patch_file"; then
		printf 'gomadv3 patch may only modify existing allowed files\n' >&2
		exit 1
	fi

	local path
	while IFS= read -r path; do
		validate_patch_path "$path"
	done < <(awk '
		$1 == "diff" && $2 == "--git" {
			print substr($3, 3)
			print substr($4, 3)
		}
		($1 == "---" || $1 == "+++") && $2 != "/dev/null" {
			path = $2
			sub(/^[ab]\//, "", path)
			print path
		}
	' "$patch_file" | sort -u)

	if awk '/^GIT binary patch/ || /^Binary files / || /^\+.*Code generated by .* DO NOT EDIT/ { found = 1 } END { exit !found }' "$patch_file"; then
		printf 'gomadv3 patch contains generated or binary output\n' >&2
		exit 1
	fi
}

validate_overlay_path() {
	local allowed
	for allowed in "${overlay_allowed_paths[@]}"; do
		if [[ $1 == "$allowed" ]]; then
			return
		fi
	done
	validate_runtime_path "$1"
	printf 'gomadv3 input touches prohibited path: %s\n' "$1" >&2
	exit 1
}

validate_overlay() {
	if [[ ! -d "$overlay_dir" ]]; then
		printf 'gomadv3 overlay is missing: %s\n' "$overlay_dir" >&2
		exit 1
	fi

	local special=
	while IFS= read -r -d '' special; do
		break
	done < <(find "$overlay_dir" -mindepth 1 ! -type d ! -type f -print0)
	if [[ -n "$special" ]]; then
		printf 'gomadv3 overlay contains a non-regular file: %s\n' "$special" >&2
		exit 1
	fi

	local count=0 file path
	while IFS= read -r -d '' file; do
		count=$((count + 1))
		path=${file#"$overlay_dir"/}
		validate_overlay_path "$path"
		if od -An -tx1 "$file" | awk '{ for (i = 1; i <= NF; i++) if ($i == "00") found = 1 } END { exit !found }'; then
			printf 'gomadv3 overlay contains binary output: %s\n' "$path" >&2
			exit 1
		fi
		if [[ $path != src/cmd/compile/internal/gomadintercept/spec_go126.go && $path != src/internal/gomadwire/wire_generated.go && $path != src/internal/gomadwire/wire_generated_test.go ]] && awk '/Code generated by .* DO NOT EDIT/ { found = 1 } END { exit !found }' "$file"; then
			printf 'gomadv3 overlay contains generated output: %s\n' "$path" >&2
			exit 1
		fi
	done < <(sorted_files "$overlay_dir")
	if ((count == 0)); then
		printf 'gomadv3 overlay contains no runtime source files\n' >&2
		exit 1
	fi
}

