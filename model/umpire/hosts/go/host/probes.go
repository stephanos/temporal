// Probe carries stateless catalog operations through the existing extension route.
func Probe(ctx context.Context, host *Host, request proto.Message) (*annotationsv1.ProbeResponse, error) {
	if request == nil || proto.Size(request) > (1<<20)-1024 {
		return nil, errors.New("probe request exceeds metadata budget")
	}
	input, err := anypb.New(request)
	if err != nil {
		return nil, err
	}
	response, err := host.Annotate(ctx, &modelv1.AnnotateRequest{Input: input})
	if err != nil {
		return nil, err
	}
	output := new(annotationsv1.ProbeResponse)
	if err := response.GetOutput().UnmarshalTo(output); err != nil {
		return nil, errors.New("decode probe response")
	}
	return output, nil
}

// ExpandProbeRecipe verifies a bounded byte assembly without interpreting its payload.
func ExpandProbeRecipe(recipe *annotationsv1.ProbeRecipe) ([]byte, error) {
	const maxExpanded = 16 << 20
	if recipe == nil || recipe.DecodedLength == 0 || recipe.DecodedLength > maxExpanded || len(recipe.Segments) == 0 || len(recipe.Segments) > 65536 {
		return nil, errors.New("invalid recipe bounds")
	}
	total := uint64(0)
	for _, segment := range recipe.Segments {
		if segment == nil || len(segment.Literal) == 0 || segment.Repeat == 0 {
			return nil, errors.New("invalid recipe segment")
		}
		total += uint64(len(segment.Literal)) * uint64(segment.Repeat)
		if total > uint64(recipe.DecodedLength) {
			return nil, errors.New("recipe exceeds declared length")
		}
	}
	if total != uint64(recipe.DecodedLength) {
		return nil, errors.New("recipe length mismatch")
	}
	output := make([]byte, 0, int(total))
	for _, segment := range recipe.Segments {
		for range segment.Repeat {
			output = append(output, segment.Literal...)
		}
	}
	hash := fnv.New64a()
	_, _ = hash.Write(output)
	if hash.Sum64() != recipe.Fnv64 {
		return nil, errors.New("recipe integrity mismatch")
	}
	return output, nil
}

// DispatchProbe sends the guest's exact generated bytes directly to the declared RPC.
// A nil response means local preparation failed before the RPC was invoked.
func DispatchProbe(ctx context.Context, connection grpc.ClientConnInterface, prepared *annotationsv1.ProbeResponse, serviceName string) (proto.Message, error) {
	parts := strings.Split(prepared.GetMethod(), "/")
	if len(parts) != 3 || parts[0] != "" || parts[1] != serviceName {
		return nil, errors.New("unsupported probe service")
	}
	service, err := protoregistry.GlobalFiles.FindDescriptorByName(protoreflect.FullName(parts[1]))
	if err != nil {
		return nil, errors.New("missing probe service descriptor")
	}
	descriptor, ok := service.(protoreflect.ServiceDescriptor)
	if !ok {
		return nil, errors.New("unsupported probe service")
	}
	method := descriptor.Methods().ByName(protoreflect.Name(parts[2]))
	if method == nil {
		return nil, errors.New("unknown probe method")
	}
	inputType, err := protoregistry.GlobalTypes.FindMessageByName(method.Input().FullName())
	if err != nil {
		return nil, errors.New("missing probe input descriptor")
	}
	outputType, err := protoregistry.GlobalTypes.FindMessageByName(method.Output().FullName())
	if err != nil {
		return nil, errors.New("missing probe output descriptor")
	}
	message := prepared.GetMessage()
	if prepared.GetRecipe() != nil {
		if len(message) != 0 {
			return nil, errors.New("ambiguous probe encoding")
		}
		message, err = ExpandProbeRecipe(prepared.Recipe)
		if err != nil {
			return nil, err
		}
	}
	input, output := inputType.New().Interface(), outputType.New().Interface()
	if err := proto.Unmarshal(message, input); err != nil {
		return nil, errors.New("malformed probe input")
	}
	return output, connection.Invoke(ctx, prepared.Method, input, output)
}

// ObserveProbe retains only status metadata; raw server messages never leave this call.
func ObserveProbe(testCase *annotationsv1.ProbeCase, rpcErr error) (*annotationsv1.ProbeObservation, error) {
	if testCase == nil || len(testCase.Id) == 0 || len(testCase.Id) > 4096 || len(testCase.Predictions) > 256 || len(testCase.Refusal) > 256 {
		return nil, errors.New("invalid probe observation metadata")
	}
	observation := &annotationsv1.ProbeObservation{
		CaseId: testCase.Id, Applicability: testCase.Applicability, Refusal: testCase.Refusal,
	}
	if testCase.Applicability != annotationsv1.ProbeApplicability_APPLICABLE {
		if !testCase.Generic || testCase.Applicability < annotationsv1.ProbeApplicability_NOT_APPLICABLE || testCase.Applicability > annotationsv1.ProbeApplicability_UNCHANGED || rpcErr != nil || len(testCase.Predictions) != 0 {
			return nil, errors.New("invalid non-dispatched probe observation")
		}
		return observation, nil
	}
	if testCase.Refusal != "" || (!testCase.Generic && len(testCase.Predictions) != 0) {
		return nil, errors.New("invalid dispatched probe observation")
	}
	if testCase.Generic && (testCase.Accepts || testCase.Code != 0 || testCase.MessagePattern != "" || testCase.DetailsType != "") {
		return nil, errors.New("mixed strict and generic probe metadata")
	}
	observation.Accepted = rpcErr == nil
	if rpcErr != nil {
		observation.Code = int32(status.Code(rpcErr))
	}
	if !testCase.Generic {
		matches, details, err := observeExpectation(testCase.Id, testCase.MessagePattern, testCase.DetailsType, rpcErr)
		if err != nil {
			return nil, err
		}
		observation.MessageMatches, observation.DetailsType = matches, details
		return observation, nil
	}
	seen := make(map[string]bool, len(testCase.Predictions))
	observation.PredictionCount = uint32(len(testCase.Predictions))
	for index, prediction := range testCase.Predictions {
		if prediction == nil || len(prediction.Id) > 4096 || !strings.HasPrefix(prediction.Id, testCase.Id+"::prediction:") || seen[prediction.Id] {
			return nil, errors.New("invalid probe prediction identity")
		}
		seen[prediction.Id] = true
		matches, details, err := observeExpectation(testCase.Id, prediction.MessagePattern, prediction.DetailsType, rpcErr)
		if err != nil {
			return nil, err
		}
		observation.Predictions = append(observation.Predictions, &annotationsv1.ProbeMatch{
			Index: uint32(index), PredictionId: prediction.Id,
			MessageMatches: matches, DetailsType: details,
		})
	}
	return observation, nil
}

func observeExpectation(caseID, messagePattern, detailsType string, rpcErr error) (bool, string, error) {
	if len(messagePattern) > 4096 || len(detailsType) > 512 {
		return false, "", errors.New("invalid probe expectation bounds")
	}
	pattern, err := regexp.Compile("(?s)^(?:.*(?:" + messagePattern + ").*)$")
	if err != nil {
		return false, "", fmt.Errorf("invalid probe pattern for %s", caseID)
	}
	if rpcErr == nil {
		return false, "", nil
	}
	rpcStatus := status.Convert(rpcErr)
	actualDetails := ""
	for _, detail := range rpcStatus.Proto().GetDetails() {
		if actualDetails == "" || detail.MessageName() == protoreflect.FullName(detailsType) {
			actualDetails = string(detail.MessageName())
		}
	}
	return pattern.MatchString(rpcStatus.Message()), actualDetails, nil
}
