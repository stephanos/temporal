//! System-owned policy and negative controls for the generic source boundary.

#![forbid(unsafe_code)]

use std::{
    collections::BTreeMap,
    fs, io,
    path::{Path, PathBuf},
};
use umpire_testing::boundary::{Violation, scan_with_exclusions};

const EXTENSIONS: &[&str] = &["rs", "proto", "go", "toml"];
const FORBIDDEN: &[&str] =
    &["temporal", "Temporal", "go.temporal.io/", "temporal.api", "temporal::api", "temporal/api"];

fn organization_path(line: &str, offset: usize) -> bool {
    let path_char = |c: char| c.is_ascii_alphanumeric() || "._/-@".contains(c);
    let start = line[..offset]
        .char_indices()
        .rfind(|(_, c)| !path_char(*c))
        .map_or(0, |(i, c)| i + c.len_utf8());
    let end = line[offset..].find(|c| !path_char(c)).map_or(line.len(), |i| offset + i);
    let token = &line[start..end];
    offset == start + "github.com/".len()
        && token.strip_prefix("github.com/temporalio/").is_some_and(|rest| !rest.is_empty())
}

fn check(root: &Path) -> io::Result<Vec<Violation>> {
    let descriptors = descriptor_lines(root)?;
    scan_with_exclusions(
        root,
        EXTENSIONS,
        FORBIDDEN,
        &[".git", "target", "build", ".bin"],
        |path, number, line, offset| {
            organization_path(line, offset)
                || (descriptors
                    .get(&(path.to_owned(), number))
                    .is_some_and(|approved| approved == line)
                    && line[..offset].ends_with("github.com/")
                    && line[offset..].starts_with("temporalio/"))
        },
    )
}

fn descriptor_lines(root: &Path) -> io::Result<BTreeMap<(PathBuf, usize), String>> {
    let policy = match fs::read_to_string(root.join("dev/gate/policy/framework-boundary.txt")) {
        Ok(policy) => policy,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(BTreeMap::new()),
        Err(error) => return Err(error),
    };
    let policy: toml::Value = toml::from_str(&policy).map_err(io::Error::other)?;
    let rows = policy
        .get("descriptor_lines")
        .and_then(toml::Value::as_array)
        .ok_or_else(|| io::Error::other("invalid framework descriptor policy"))?;
    let mut allowed = BTreeMap::new();
    let canonical = root.canonicalize()?;
    for row in rows {
        let relative = row
            .get("path")
            .and_then(toml::Value::as_str)
            .ok_or_else(|| io::Error::other("invalid descriptor policy path"))?;
        let expected = row
            .get("sha256")
            .and_then(toml::Value::as_str)
            .ok_or_else(|| io::Error::other("invalid descriptor policy hash"))?;
        let path = Path::new(relative);
        if path.components().any(|part| !matches!(part, std::path::Component::Normal(_)))
            || !root.join(path).canonicalize()?.starts_with(&canonical)
        {
            return Err(io::Error::other("escaping descriptor policy path"));
        }
        let source = fs::read_to_string(root.join(path))?;
        if !source.starts_with("// Code generated by protoc-gen-go. DO NOT EDIT.\n") {
            continue;
        }
        let mut descriptor = false;
        for (number, line) in source.lines().enumerate() {
            if line.starts_with("const file_") && line.ends_with("_rawDesc = \"\" +") {
                descriptor = true;
            } else if descriptor && line.starts_with("\t\"") {
                if umpire_tla::process::bytes_sha256(line.as_bytes()) == expected {
                    allowed.insert((path.to_owned(), number + 1), line.to_owned());
                }
            } else {
                descriptor = false;
            }
        }
    }
    Ok(allowed)
}

#[test]
fn generic_source_boundary() -> umpire_testing::TestResult {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../../umpire");
    let violations = check(&root)?;
    assert!(
        violations.is_empty(),
        "{}",
        violations.iter().map(ToString::to_string).collect::<Vec<_>>().join("\n")
    );
    Ok(())
}

#[test]
fn boundary_controls() -> umpire_testing::TestResult {
    let root = std::env::temp_dir().join(format!("umpire-boundary-{}", std::process::id()));
    fs::create_dir_all(root.join("nested"))?;
    let result = (|| -> umpire_testing::TestResult {
        for extension in EXTENSIONS {
            fs::write(
                root.join(format!("nested/source.{extension}")),
                "ordinary\nTemporalClient temporal_client\nuse temporal::api;\nimport go.temporal.io/api;\nmodule temporal/api;\n// temporal.api.Workflow\n",
            )?;
        }
        let paths = [
            "github.com/temporalio/umpire",
            "github.com/temporalio/umpire/hosts/go",
            "temporalio",
            "github.com/temporalioish/umpire",
            "github.com/Temporalio/umpire",
            "github.com/temporalio",
            "github.com/temporalio/",
            "other/temporalio/umpire",
            "other/github.com/temporalio/umpire",
            "github.com/temporalio/Temporal",
            "github.com/temporalio/temporal",
            "github.com/temporalio/umpire Temporal",
            "github.com/temporalio/umpire_temporal",
            "github.com/temporalio/umpire temporalio",
        ];
        fs::write(root.join("paths.toml"), paths.join("\n"))?;
        fs::write(root.join("ignored.txt"), "Temporal")?;
        let mut expected = Vec::new();
        for extension in ["go", "proto", "rs", "toml"] {
            for line in 2..=6 {
                expected
                    .push(Violation { path: format!("nested/source.{extension}").into(), line });
            }
        }
        for line in 3..=paths.len() {
            expected.push(Violation { path: "paths.toml".into(), line });
        }
        let actual = check(&root)?;
        assert_eq!(actual, expected);
        assert_eq!(check(&root)?, actual);
        assert_eq!(actual[0].to_string(), "nested/source.go:2: forbidden source dependency");
        Ok(())
    })();
    fs::remove_dir_all(&root)?;
    result
}

#[test]
fn descriptor_controls() -> umpire_testing::TestResult {
    let root =
        std::env::temp_dir().join(format!("umpire-descriptor-boundary-{}", std::process::id()));
    fs::create_dir_all(root.join("dev/gate/policy"))?;
    fs::create_dir_all(root.join("nested"))?;
    let result = (|| -> umpire_testing::TestResult {
        let line = "\t\"\\x06proto3ZAgithub.com/temporalio/umpire/hosts/go;modelv1\"";
        let header = "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage control\nconst file_control_rawDesc = \"\" +\n";
        let policy = |line: &str| {
            format!(
                "[[descriptor_lines]]\npath = \"nested/descriptor.go\"\nsha256 = \"{}\"\n",
                umpire_tla::process::bytes_sha256(line.as_bytes())
            )
        };
        let descriptor = root.join("nested/descriptor.go");
        let policy_path = root.join("dev/gate/policy/framework-boundary.txt");
        fs::write(&descriptor, format!("{header}{line}\n"))?;
        fs::write(&policy_path, policy(line))?;
        assert_eq!(check(&root)?, []);

        fs::write(root.join("nested/copied.go"), format!("{line}\n"))?;
        assert_eq!(check(&root)?, [Violation { path: "nested/copied.go".into(), line: 1 }]);
        fs::remove_file(root.join("nested/copied.go"))?;
        fs::write(&descriptor, format!("{header}{line}\n\n{line}\n"))?;
        assert_eq!(check(&root)?, [Violation { path: "nested/descriptor.go".into(), line: 6 }]);

        fs::write(&descriptor, format!("{header}{line}\n// Temporal\n"))?;
        assert_eq!(check(&root)?.len(), 1);

        let forbidden = line.replace("/umpire/", "/Temporal/");
        fs::write(&descriptor, format!("{header}{forbidden}\n"))?;
        fs::write(&policy_path, policy(&forbidden))?;
        assert_eq!(check(&root)?.len(), 1);

        fs::write(&descriptor, format!("{header}{line}\n"))?;
        assert_eq!(check(&root)?.len(), 1);

        fs::write(&policy_path, policy(line))?;
        fs::write(
            &descriptor,
            format!("// Code generated by protoc-gen-go. DO NOT EDIT.\n{line}\n"),
        )?;
        assert_eq!(check(&root)?.len(), 1);

        fs::write(
            &descriptor,
            format!("package control\nconst file_control_rawDesc = \"\" +\n{line}\n"),
        )?;
        assert_eq!(check(&root)?.len(), 1);
        Ok(())
    })();
    fs::remove_dir_all(&root)?;
    result
}
